    this.table,
    this.fields,
    this.keys,
    this.constructor,
    this.module,
    this.tokenizer,
    this.scalars,
  );
  final ClassElement element;
  final String table;
  final List<_Field> fields, keys;
  final ConstructorElement constructor;
  final String? module;
  final String? tokenizer;
  final List<_Scalar> scalars;
  String get name => element.name!;
}

final class _Relationship {
  _Relationship(
    this.child,
    this.parent,
    this.field,
    this.target,
    this.helper,
    this.action,
  );
  final _Model child, parent;
  final _Field field, target;
  final String helper, action;
}

String _emit(
  String input,
  String output,
  String prefix,
  String listName,
  List<_Model> models,
  List<_Relationship> relationships, {
  required bool annotatedOnly,
  required Iterable<String> classNames,
}) {
  final dynamicName = '${listName.substring(0, listName.length - 4)}dynamic';
  final code = StringBuffer(_header)
    ..writeln(
      _stampLine(
        _sourceDigest(
          input,
          annotatedOnly: annotatedOnly,
          classNames: classNames,
        ),
        models.map((model) => model.name),
      ),
    )
    ..writeln()
    ..writeln('part of ${_string(_relative(input, p.dirname(output)))};');
  for (final model in models) {
    code.writeln('abstract final class ${model.name}Columns {');
    for (final field in model.fields) {
      code.writeln(
        'static final ${prefix}Column<${model.name}, ${field.dartType}> '
        '${field.name} = ${prefix}Column<${model.name}, ${field.dartType}>('
        'property: ${_string(field.name)}, name: ${_string(field.sqlName)}, '
        'codec: ${field.codec(prefix)}, read: (entity) => entity.${field.name}, '
        '${field.writable ? 'write: (entity, value) => entity.${field.name} = value,' : ''}'
        '${field.keyOrder != null ? 'keyOrder: ${field.keyOrder},' : ''}'
        '${field.generated ? 'generated: true,' : ''}'
        '${field.version ? 'version: true,' : ''}'
        '${field.unique ? 'unique: true,' : ''}'
        '${field.defaultSql != null ? 'defaultSql: ${_string(field.defaultSql!)},' : ''}'
        '${field.vectorDimensions == null ? '' : 'vectorDimensions: ${field.vectorDimensions}, vectorMetric: ${_string(field.vectorMetric!)},'}'
        ');',
      );
    }
    code.writeln(
      'static final $listName<${prefix}Column<${model.name}, $dynamicName>> all = '
      '$listName.unmodifiable([${model.fields.map((field) => field.name).join(',')}]);}',
    );
    code.writeln('abstract final class ${model.name}Mapping {');
    code.writeln(
      'static final ${prefix}EntityType<${model.name}> instance = '
      '${prefix}EntityType<${model.name}>(tableName: ${_string(model.table)},'
      'columns: ${model.name}Columns.all, create: _create,'
      '${model.module == null ? '' : 'virtualModule: ${_string(model.module!)},'}'
      '${model.tokenizer == null ? '' : 'tokenizer: ${_string(model.tokenizer!)},'}'
      '${model.fields.any((field) => !field.writable) ? 'applyStoreValues: (entity, row) => _create(row),' : ''}'
      '${model.scalars.isEmpty ? '' : 'scalars: _scalars,'}'
      ');',
    );
    code.writeln('static ${model.name} _create(${prefix}RowReader row) {');
    final parameters = <String>[];
    for (final parameter in model.constructor.formalParameters) {
      final field = model.fields
          .where((field) => field.name == parameter.name)
          .firstOrNull;
      if (field == null) continue;
      final value = 'row.read(${model.name}Columns.${field.name})';
      parameters.add(parameter.isNamed ? '${parameter.name}: $value' : value);
    }
    code.writeln(
      'final entity = ${model.name}'
      '${_unnamedConstructor(model.constructor) ? '' : '.${model.constructor.name}'}'
      '(${parameters.join(',')});',
    );
    for (final field in model.fields.where((field) => field.writable)) {
      code.writeln(
        'entity.${field.name} = row.read(${model.name}Columns.${field.name});',
      );
    }
    code.writeln('return entity; }');
    if (model.scalars.isNotEmpty) {
      code.writeln(
        'static final _scalars = $listName<${prefix}EntityScalar<${model.name}>>.unmodifiable([',
      );
      for (final scalar in model.scalars) {
        code.writeln(_scalarRegistration(model, scalar, prefix));
      }
      code.writeln(']);');
    }
    code.writeln(
      'static ${prefix}EntityKey key('
      '${[for (var i = 0; i < model.keys.length; i++) '${model.keys[i].keyType} value$i'].join(',')}'
      ') => ${prefix}EntityKey(['
      '${[for (var i = 0; i < model.keys.length; i++) '${model.name}Columns.${model.keys[i].name}.codec.encode(value$i)'].join(',')}'
      ']);}',
    );
    final related = relationships.where((relation) => relation.child == model);
    if (related.isNotEmpty) {
      code.writeln('abstract final class ${model.name}Relationships {');
      for (final relation in related) {
        code.writeln(
          'static final ${prefix}ForeignKey<${model.name}, ${relation.parent.name}> '
          '${relation.helper} = ${prefix}ForeignKey<${model.name}, ${relation.parent.name}>('
          'name: ${_string('${model.name}_${relation.field.name}_${relation.parent.name}')},'
          'child: ${model.name}Mapping.instance, parent: ${relation.parent.name}Mapping.instance,'
          'columns: [${model.name}Columns.${relation.field.name}],'
          'targetColumns: [${relation.parent.name}Columns.${relation.target.name}],'
          'onDelete: ${prefix}ForeignKeyAction.${relation.action},);',
        );
      }
      code.writeln('}');
    }
    code.writeln('final class ${model.name}Fields {');
    code.writeln('${model.name}Fields._();');
    code.writeln('static final instance = ${model.name}Fields._();');
    for (final field in model.fields) {
      final wrapper = field.document ? 'DocumentField' : 'MappedField';
      code.writeln(
        'final ${field.name} = $prefix$wrapper(${model.name}Columns.${field.name});',
      );
    }
    final json = model.fields.where((field) => field.json).toList();
    if (json.length == 1) {
      code.writeln(
        '${prefix}JsonPathField<${model.name}> path(String path) => ${json.single.name}.at(path);',
      );
    } else {
      for (final field in json) {
        code.writeln(
          '${prefix}JsonPathField<${model.name}> ${field.name}Path(String path) => ${field.name}.at(path);',
        );
      }
    }
    if (model.module == 'rtree') {
      code.writeln(
        'final bounds = ${prefix}Bounds<${model.name}>('
        'minX: ${model.name}Columns.minX, maxX: ${model.name}Columns.maxX, '
        'minY: ${model.name}Columns.minY, maxY: ${model.name}Columns.maxY,);',
      );
    }
    for (final scalar in model.scalars) {
      final arguments = scalar.fields.isEmpty
          ? '<${prefix}SqlArgument<${model.name}>>[]'
          : '[${scalar.fields.map((field) => '${prefix}SqlArgument.of(${field.name})').join(', ')}]';
      code.writeln(
        '${prefix}SqlCall<${model.name}, ${scalar.returnType}> ${scalar.name}() => '
        '${prefix}SqlCall(${_string(scalar.sqlName)}, $arguments);',
      );
    }
    code.writeln('}');
    code.writeln(
      'extension ${model.name}Query on ${prefix}TypedQuery<${model.name}> {',
    );
    for (final name in ['filter', 'selectWhere']) {
      code.writeln(
        '${prefix}TypedQuery<${model.name}> $name(${prefix}SqlPredicate<${model.name}> Function(${model.name}Fields row) build) { return andWhere(build(${model.name}Fields.instance)); }',
      );
    }
    code.writeln(
      '${prefix}TypedQuery<${model.name}> orderByFields($listName<${prefix}SqlOrdering<${model.name}>> Function(${model.name}Fields row) build) { return sortBy(build(${model.name}Fields.instance)); }',
    );
    if (model.module == 'fts5') {
      code.writeln(
        '${prefix}TypedQuery<${model.name}> search(String text) => ${prefix}TypedQuery<${model.name}>(type: type, connection: connection).search(text);',
      );
    }
    if (model.module == 'vec0') {
      code.writeln(
        '${prefix}TypedQuery<${model.name}> nearest(List<double> vector, {int k = 10}) => ${prefix}TypedQuery<${model.name}>(type: type, connection: connection).nearest(vector, k: k);',
      );
    }
    code.writeln('}');
  }
  code.writeln(
    'final ${prefix}DbModel generatedModel = ${prefix}DbModel(['
    '${models.map((model) => '${model.name}Mapping.instance').join(',')}],'
    'foreignKeys: ['
    '${relationships.map((relation) => '${relation.child.name}Relationships.${relation.helper}').join(',')}]);',
  );
  return code.toString();
}
