const _ormUri = 'package:sqlite_plus_orm/sqlite_plus_orm.dart';
const _header =
    '// GENERATED CODE - DO NOT MODIFY BY HAND.\n'
    '// Generated by sqlite_plus_generator.\n';

/// Resolve a Dart library and build its ORM part without modifying any files.
///
/// The source must import sqlite_plus_orm and declare the output as a `part`.
/// Annotations are optional: a public concrete class with one conventional `id`
/// or `<ClassName>Id` field is selected by default. [classNames] selects an
/// explicit set instead. Unsupported mappings produce located diagnostics.
Future<GenerationResult> generateLibrary(
  String inputPath, {
  Iterable<String> classNames = const [],
  String? outputPath,
}) async {
  final input = p.normalize(p.absolute(inputPath));
  final output = p.normalize(
    p.absolute(
      outputPath ??
          p.join(
            p.dirname(input),
            '${p.basenameWithoutExtension(input)}.orm.g.dart',
          ),
    ),
  );
  if (input == output) {
    _fail('G001', 'Input and output must be different files.', input);
  }
  if (!File(input).existsSync()) {
    _fail('G001', 'Input file does not exist.', input);
  }
  _checkOutputOwnership(output);
  final resolved = await resolveFile(path: input);
  if (resolved is! ResolvedUnitResult) {
    _fail('G001', 'The input could not be resolved as a Dart library.', input);
  }
  final result = resolved;
  if (result.unit.directives.any((directive) => directive is PartOfDirective)) {
    _fail('G002', 'Generate the containing library, not a part file.', input);
  }
  final outputParts = result.unit.directives.whereType<PartDirective>().where(
    (part) =>
        p.normalize(p.join(p.dirname(input), part.uri.stringValue ?? '')) ==
        output,
  );
  if (outputParts.isEmpty) {
    _fail(
      'G002',
      'Add part ${_string(_relative(output, p.dirname(input)))} to the source.',
      input,
    );
  }
  final libraryResult = await result.session.getResolvedLibraryByElement(
    result.libraryElement,
  );
  if (libraryResult is! ResolvedLibraryResult) {
    _fail('G001', 'The containing library could not be resolved.', input);
  }
  final units = {
    for (final unit in libraryResult.units) p.normalize(unit.path): unit,
  };
  final sourceErrors = <GeneratorDiagnostic>[];
  for (final unit in units.values) {
    if (p.normalize(unit.path) == output) continue;
    for (final error in unit.diagnostics) {
      final code = error.diagnosticCode;
      if (code.severity != DiagnosticSeverity.ERROR) continue;
      if (unit.path == input &&
          const {
            'uri_does_not_exist',
            'uri_has_not_been_generated',
            'part_of_different_library',
            'part_of_non_part',
            'part_of_unnamed_library',
          }.contains(code.lowerCaseName) &&
          outputParts.any(
            (part) => error.offset >= part.offset && error.offset < part.end,
          )) {
        continue;
      }
      final location = unit.lineInfo.getLocation(error.offset);
      sourceErrors.add(
        GeneratorDiagnostic(
          'G003',
          error.message,
          unit.path,
          location.lineNumber,
          location.columnNumber,
          offset: error.offset,
        ),
      );
    }
  }
  if (sourceErrors.isNotEmpty) throw GenerationException(sourceErrors);
  final library = result.libraryElement;
  final prefix = _runtimePrefix(library, input);
  final listName = _listName(library, input);
  final inspector = _Inspector(units, output, library);
  final requested = classNames.toSet();
  final classes = library.fragments
      .where((unit) => p.normalize(unit.source.fullName) != output)
      .expand((unit) => unit.classes)
      .map((fragment) => fragment.element)
      .toList();
  final selected = <ClassElement>[];
  for (final element in classes) {
    final explicitlySelected = requested.contains(element.name);
    if (explicitlySelected ||
        requested.isEmpty &&
            !element.isPrivate &&
            (_annotation(element, 'DbEntity') != null ||
                !element.isAbstract && _conventionalKeys(element).isNotEmpty)) {
      selected.add(element);
    }
  }
  for (final missing in requested.difference(
    classes.map((element) => element.name).whereType<String>().toSet(),
  )) {
    inspector.error('G004', 'No class named $missing exists in this library.');
  }
  if (selected.isEmpty && inspector.diagnostics.isEmpty) {
    inspector.error(
      'G004',
      'No models selected. Add a conventional id, @DbEntity, or --class.',
    );
  }
  final models = <_Model>[];
  for (final element in selected) {
    try {
      models.add(inspector.inspect(element));
    } on _InvalidModel {
      // Retain one actionable mapping diagnostic per invalid model.
    }
  }
  inspector.checkModelNames(models, library);
  final relationships = inspector.relationships(models);
  if (inspector.diagnostics.isNotEmpty) {
    throw GenerationException(inspector.diagnostics);
  }
  _requireRuntimeNames(library, prefix, [
    if (models.any((model) => model.fields.any((field) => field.json)))
      'JsonPathField',
    if (models.any((model) => model.module == 'rtree')) 'Bounds',
  ], input);
  final emitted = _emit(input, output, prefix, listName, models, relationships);
  return GenerationResult(
    input,
    output,
    DartFormatter(
      languageVersion: DartFormatter.latestLanguageVersion,
    ).format(emitted),
    models.map((model) => model.name),
  );
}

/// Write a validated generated part atomically, or compare it in [check] mode.
///
/// Returns false only when [check] finds a missing or stale output. Existing
/// hand-written files, directories and symbolic links are never overwritten.
Future<bool> writeGenerated(
  GenerationResult result, {
  bool check = false,
}) async {
  _checkOutputOwnership(result.outputPath);
  final output = File(result.outputPath);
  final current = output.existsSync()
      ? utf8.decode(output.readAsBytesSync(), allowMalformed: true)
      : null;
  if (current == result.code) return true;
  if (check) return false;
  await output.parent.create(recursive: true);
  final temporaryDirectory = await output.parent.createTemp(
    '.sqlite-plus-generator-',
  );
  final temporary = File(p.join(temporaryDirectory.path, 'output.dart'));
  try {
    await temporary.writeAsString(result.code, flush: true);
    // Recheck after the asynchronous write, before replacing the destination.
    _checkOutputOwnership(result.outputPath);
    await temporary.rename(output.path);
  } finally {
    await temporaryDirectory.delete(recursive: true);
  }
  return true;
}

void _checkOutputOwnership(String output) {
  final kind = FileSystemEntity.typeSync(output, followLinks: false);
  if (kind == FileSystemEntityType.notFound) return;
  if (kind != FileSystemEntityType.file) {
    _fail('G020', 'Output must be an ordinary generated file.', output);
  }
  final contents = File(output).readAsBytesSync();
  final signature = _header.codeUnits;
  if (contents.length < signature.length ||
      List.generate(
        signature.length,
        (index) => index,
      ).any((index) => contents[index] != signature[index])) {
    _fail(
      'G020',
      'Refusing to replace a file without the generator header.',
      output,
    );
  }
}

Never _fail(String code, String message, String path) =>
    throw GenerationException([GeneratorDiagnostic(code, message, path, 1, 1)]);

String _relative(String path, String from) =>
    p.relative(path, from: from).replaceAll('\\', '/');

String _string(String value) => jsonEncode(value).replaceAll(r'$', r'\$');

String _lower(String value) =>
    value.replaceAllMapped(RegExp('[A-Z]'), (match) => match[0]!.toLowerCase());

String _libraryUri(LibraryElement library) =>
    library.firstFragment.source.uri.toString();

String _elementPath(Element element) =>
    element.firstFragment.libraryFragment?.source.fullName ?? '';

int _nameOffset(Element element) => element.firstFragment.nameOffset ?? 0;

bool _unnamedConstructor(ConstructorElement constructor) =>
    constructor.name == null || constructor.name == 'new';

List<LibraryImport> _imports(LibraryElement library) =>
    library.firstFragment.libraryImports;

bool _importDeferred(LibraryImport import) =>
    import.prefix?.isDeferred ?? false;

String? _importPrefix(LibraryImport import) => import.prefix?.name;

Element? _importLookup(LibraryImport import, String name) {
  final prefix = _importPrefix(import);
  return import.namespace.get2(prefix == null ? name : '$prefix.$name');
}

Iterable<Element> _topLevel(LibraryElement library) => [
  ...library.classes,
  ...library.enums,
  ...library.mixins,
  ...library.extensions,
  ...library.extensionTypes,
  ...library.topLevelFunctions,
  ...library.topLevelVariables,
  ...library.typeAliases,
  ...library.getters,
  ...library.setters,
];

DartObject? _annotation(Element element, String name) {
  for (final annotation in element.metadata.annotations) {
    final value = annotation.computeConstantValue();
    final type = value?.type;
    if (type is InterfaceType &&
        type.element.name == name &&
        _libraryUri(type.element.library) == _ormUri) {
      return value;
    }
  }
  return null;
}

List<FieldElement> _fields(ClassElement element) => element.fields
    .where(
      (field) =>
          field.name != null &&
          !field.isStatic &&
          !field.isPrivate &&
          !field.isOriginGetterSetter &&
          !field.isOriginEnumValues &&
          _annotation(field, 'DbIgnore') == null,
    )
    .toList();

List<FieldElement> _conventionalKeys(ClassElement element) => _fields(element)
    .where(
      (field) =>
          _lower(field.name!) == 'id' ||
          _lower(field.name!) == '${_lower(element.name!)}id',
    )
    .toList();

String _runtimePrefix(LibraryElement library, String input) {
  const names = [
    'Column',
    'EntityType',
    'RowReader',
    'Codecs',
    'EntityKey',
    'DbModel',
    'ForeignKey',
    'ForeignKeyAction',
    'MappedField',
    'SqlPredicate',
    'TypedQuery',
    'SqlOrdering',
  ];
  final imports = [..._imports(library)]
    ..sort(
      (a, b) => (a.prefix == null ? 1 : 0).compareTo(b.prefix == null ? 1 : 0),
    );
  for (final import in imports) {
    if (_importDeferred(import)) continue;
    if (import.prefix == null &&
        _topLevel(library).any(
          (element) =>
              names.contains(element.name) &&
              (element.library == null ||
                  _libraryUri(element.library!) != _ormUri),
        )) {
      continue;
    }
    if (names.every((name) {
      final element = _importLookup(import, name);
      return element is InterfaceElement &&
          _libraryUri(element.library) == _ormUri &&
          (import.prefix != null || _visibleUnprefixed(library, name, element));
    })) {
      final prefix = _importPrefix(import);
      return prefix == null ? '' : '$prefix.';
    }
  }
  _fail(
    'G002',
    'Import the public sqlite_plus_orm runtime eagerly without hiding its '
        'metadata types (an import prefix is supported).',
    input,
  );
}

String _listName(LibraryElement library, String input) {
  for (final import in _imports(library)) {
    if (_importDeferred(import)) continue;
    final prefix = _importPrefix(import);
    final name = prefix == null ? 'List' : '$prefix.List';
    final element = _importLookup(import, 'List');
    if (element is InterfaceElement &&
        _libraryUri(element.library) == 'dart:core' &&
        (prefix != null || _visibleUnprefixed(library, 'List', element))) {
      return name;
    }
  }
  _fail(
    'G011',
    'The core List type is hidden. Import dart:core with a prefix '
        'or use manual metadata.',
    input,
  );
}

void _requireRuntimeNames(
  LibraryElement library,
  String prefix,
  List<String> names,
  String input,
) {
  for (final name in names) {
    var found = false;
    for (final import in _imports(library)) {
      if (_importDeferred(import)) continue;
      final importPrefix = _importPrefix(import);
      final qualified = importPrefix == null ? '' : '$importPrefix.';
      if (qualified != prefix) continue;
      final element = _importLookup(import, name);
      if (element is InterfaceElement &&
          _libraryUri(element.library) == _ormUri) {
        found = true;
        break;
      }
    }
    if (!found) {
      _fail(
        'G002',
        'Import $name from sqlite_plus_orm. The generated mapping uses it.',
        input,
      );
    }
  }
}

bool _visibleUnprefixed(
  LibraryElement library,
  String name,
  Element expected,
) =>
    !_topLevel(library).any((element) => element.name == name) &&
    _imports(library).where((import) => import.prefix == null).every((import) {
      final element = _importLookup(import, name);
      return element == null || element == expected;
    });

final class _InvalidModel implements Exception {}

final class _Inspector {
  _Inspector(this.units, this.output, this.library);
  final Map<String, ResolvedUnitResult> units;
  final String output;
  final LibraryElement library;
  final List<GeneratorDiagnostic> diagnostics = [];

  void error(String code, String message, [Element? element]) {
    final path = element == null ? units.keys.first : _elementPath(element);
    final resolvedPath = path.isEmpty ? units.keys.first : path;
    final unit = units[p.normalize(resolvedPath)];
    final offset = element == null ? 0 : _nameOffset(element);
    final location = unit?.lineInfo.getLocation(offset);
    diagnostics.add(
      GeneratorDiagnostic(
        code,
        message,
        resolvedPath,
        location?.lineNumber ?? 1,
        location?.columnNumber ?? 1,
        offset: offset,
      ),
    );
  }

  Never invalid(String code, String message, Element element) {
    error(code, message, element);
    throw _InvalidModel();
  }

  _Model inspect(ClassElement element) {
    if (element.isPrivate ||
        element.isAbstract ||
        element.typeParameters.isNotEmpty ||
        element.mixins.isNotEmpty ||
        (element.supertype?.element.name != 'Object' ||
            _libraryUri(element.supertype!.element.library) != 'dart:core')) {
      invalid(
        'G005',
        'Models must be public concrete nongeneric classes '
            'without inherited or mixed-in storage.',
        element,
      );
    }
    final columns = <_Field>[];
    for (final field in _fields(element)) {
      final kind = _kind(field.type);
      if (kind == null) {
        invalid(
          'G006',
          'Unsupported persisted type '
              '${field.type.getDisplayString()}. '
              'Use explicit manual metadata for custom codecs.',
          field,
        );
      }
      final column = _annotation(field, 'DbColumn');
      final key = _annotation(field, 'DbKey');
      final name = column?.getField('name')?.toStringValue() ?? field.name!;
      if (!_validSqlName(name)) {
        invalid(
          'G007',
          'SQL column names must be nonempty and contain no NUL.',
          field,
        );
      }
      if (const {
        'all',
        'hashCode',
        'runtimeType',
        'toString',
        'noSuchMethod',
      }.contains(field.name)) {
        invalid(
          'G011',
          'The property ${field.name} conflicts with a generated helper. '
              'Use manual metadata for this property.',
          field,
        );
      }
      final defaultSql = column?.getField('defaultSql')?.toStringValue();
      if (defaultSql != null &&
          (defaultSql.trim().isEmpty || defaultSql.contains('\u0000'))) {
        invalid(
          'G007',
          'Default SQL must be nonempty and contain no NUL.',
          field,
        );
      }
      columns.add(
        _Field(
          field,
          kind,
          sourceType(field),
          sourceType(field, canonical: true, nonNullable: true),
          nullable: field.type.nullabilitySuffix == NullabilitySuffix.question,
          sqlName: name,
          defaultSql: defaultSql,
          unique: column?.getField('unique')?.toBoolValue() ?? false,
          keyOrder: key?.getField('order')?.toIntValue(),
          generated: key?.getField('generated')?.toBoolValue() ?? false,
          explicitKey: key != null,
          version: _annotation(field, 'DbVersion') != null,
          json: _annotation(field, 'DbJson') != null,
          reference: _annotation(field, 'DbReference'),
        ),
      );
    }
    final names = <String>{};
    for (final field in columns) {
      if (!names.add(_lower(field.sqlName))) {
        invalid(
          'G007',
          'Duplicate SQL column name ${field.sqlName}.',
          field.element,
        );
      }
    }
    final explicitKeys = columns.where((field) => field.explicitKey).toList();
    if (explicitKeys.isEmpty) {
      final conventional = _conventionalKeys(element);
      if (conventional.length != 1) {
        invalid(
          'G008',
          'A model needs exactly one conventional id/ClassNameId '
              'or explicit ordered @DbKey annotations.',
          element,
        );
      }
      final key = columns.firstWhere(
        (field) => field.element == conventional.single,
      );
      key.keyOrder = 0;
      key.generated = key.nullable && ['bigInt', 'integer'].contains(key.kind);
    }
    final keys = columns.where((field) => field.keyOrder != null).toList()
      ..sort((a, b) => a.keyOrder!.compareTo(b.keyOrder!));
    for (var i = 0; i < keys.length; i++) {
      if (keys[i].keyOrder != i) {
        invalid(
          'G008',
          'Key orders must be unique and consecutive from zero.',
          keys[i].element,
        );
      }
    }
    for (final field in columns) {
      if (field.generated &&
          (keys.length != 1 ||
              field.keyOrder != 0 ||
              !field.nullable ||
              !['bigInt', 'integer'].contains(field.kind))) {
        invalid(
          'G009',
          'Only one nullable int/BigInt primary key can be generated.',
          field.element,
        );
      }
      if (field.version &&
          (field.nullable ||
              field.keyOrder != null ||
              !['bigInt', 'integer'].contains(field.kind))) {
        invalid(
          'G009',
          'A version must be a nonnullable int/BigInt non-key field.',
          field.element,
        );
      }
    }
    if (columns.where((field) => field.version).length > 1) {
      invalid('G009', 'A model can have only one version field.', element);
    }
    final module = _annotation(
      element,
      'DbEntity',
    )?.getField('module')?.toStringValue();
    _checkVirtual(element, columns, module);
    final constructors = element.constructors
        .where((ctor) => !ctor.isFactory)
        .toList();
    bool usable(ConstructorElement ctor) {
      var unmappedPositional = false;
      for (final parameter in ctor.formalParameters.where(
        (parameter) => parameter.isPositional,
      )) {
        if (columns.any((field) => field.name == parameter.name)) {
          if (unmappedPositional) return false;
        } else {
          unmappedPositional = true;
        }
      }
      final mapped = ctor.formalParameters.map((param) => param.name).toSet();
      return ctor.formalParameters.every(
            (param) =>
                !param.isRequiredNamed && !param.isRequiredPositional ||
                columns.any((field) => field.name == param.name),
          ) &&
          ctor.formalParameters.every((param) {
            final field = columns
                .where((field) => field.name == param.name)
                .firstOrNull;
            return field == null ||
                units.values.first.typeSystem.isAssignableTo(
                  field.element.type,
                  param.type,
                );
          }) &&
          columns.every(
            (field) =>
                field.writable ||
                mapped.contains(field.name) &&
                    directlyInitializes(ctor, field.element),
          );
    }

    final candidates = constructors.where(usable).toList();
    final unnamed = candidates.where(_unnamedConstructor).toList();
    final constructor = unnamed.isNotEmpty
        ? unnamed.single
        : candidates.length == 1
        ? candidates.single
        : null;
    if (constructor == null) {
      invalid(
        'G010',
        'No unambiguous generative constructor maps every required '
            'parameter and final persisted field.',
        element,
      );
    }
    final table =
        _annotation(element, 'DbEntity')?.getField('table')?.toStringValue() ??
        element.name!;
    if (!_validSqlName(table) || _lower(table).startsWith('sqlite_')) {
      invalid(
        'G007',
        'Table names must be nonempty, contain no NUL and avoid sqlite_.',
        element,
      );
    }
    return _Model(element, table, columns, keys, constructor, module);
  }

  void _checkVirtual(
    ClassElement element,
    List<_Field> columns,
    String? module,
  ) {
    if (module == null) {
      final json = columns.where((field) => field.json).toList();
      if (json.any((field) => field.kind != 'text')) {
        invalid('G013', '@DbJson needs a String column.', element);
      }
      if (json.length == 1 &&
          (json.single.name == 'path' ||
              columns.any((field) => field.name == 'path'))) {
        invalid(
          'G011',
          'The property path conflicts with the JSON helper. '
              'Use manual metadata for this property.',
          element,
        );
      }
      if (json.length > 1 &&
          json.any(
            (field) =>
                columns.any((other) => other.name == '${field.name}Path'),
          )) {
        invalid(
          'G011',
          'A JSON helper name conflicts with a mapped property.',
          element,
        );
      }
      return;
    }
    if (module != 'fts5' && module != 'rtree') {
      invalid('G013', 'DbEntity.module must be fts5 or rtree.', element);
    }
    if (columns.any(
      (field) =>
          field.json ||
          field.version ||
          field.unique ||
          field.defaultSql != null ||
          field.reference != null,
    )) {
      invalid(
        'G013',
        'A virtual table cannot map JSON, version, unique, default, '
            'or reference columns.',
        element,
      );
    }
    if (module == 'fts5') {
      final content = columns.where((field) => field.keyOrder == null);
      if (columns.where((field) => field.keyOrder != null).length != 1 ||
          _lower(
                columns.firstWhere((field) => field.keyOrder != null).sqlName,
              ) !=
              'rowid' ||
          content.isEmpty ||
          content.any((field) => field.kind != 'text')) {
        invalid(
          'G013',
          'fts5 needs one rowid key and one or more String columns.',
          element,
        );
      }
      return;
    }
    const bounds = ['minX', 'maxX', 'minY', 'maxY'];
    final coordinates = columns.where((field) => field.keyOrder == null);
    final key = columns.where((field) => field.keyOrder != null).toList();
    if (columns.first.keyOrder == null ||
        key.length != 1 ||
        key.single.generated ||
        !const {'integer', 'bigInt'}.contains(key.single.kind) ||
        coordinates.length != bounds.length ||
        !bounds.every(
          (name) => coordinates.any(
            (field) => field.name == name && field.kind == 'real',
          ),
        ) ||
        columns.any((field) => field.name == 'bounds')) {
      invalid(
        'G013',
        'rtree needs an integer key first, then double minX, maxX, minY, and maxY.',
        element,
      );
    }
  }

  bool directlyInitializes(ConstructorElement constructor, FieldElement field) {
    final parameter = constructor.formalParameters
        .where((parameter) => parameter.name == field.name)
        .firstOrNull;
    if (parameter is FieldFormalParameterElement && parameter.field == field) {
      return true;
    }
    final unit =
        units[p.normalize(
          constructor.firstFragment.libraryFragment.source.fullName,
        )]!;
    for (final declaration
        in unit.unit.declarations.whereType<ClassDeclaration>()) {
      for (final member
          in declaration.body.members.whereType<ConstructorDeclaration>()) {
        if (member.declaredFragment?.element != constructor) continue;
        return member.initializers.whereType<ConstructorFieldInitializer>().any(
          (initializer) {
            final expression = initializer.expression;
            return initializer.fieldName.name == field.name &&
                expression is SimpleIdentifier &&
                expression.element == parameter;
          },
        );
      }
    }
    return false;
  }

  String sourceType(
    FieldElement field, {
    bool canonical = false,
    bool nonNullable = false,
  }) {
    final unit =
        units[p.normalize(field.firstFragment.libraryFragment.source.fullName)];
    for (final declaration
        in unit!.unit.declarations.whereType<ClassDeclaration>()) {
      for (final member
          in declaration.body.members.whereType<FieldDeclaration>()) {
        if (member.fields.variables.any(
          (variable) => variable.declaredFragment?.element == field,
        )) {
          final annotation = member.fields.type;
          if (annotation != null && !canonical) return annotation.toSource();
        }
      }
    }
    final type = field.type as InterfaceType;
    final name = type.element.name!;
    for (final import in _imports(library)) {
      if (_importDeferred(import)) continue;
      if (_importLookup(import, name) == type.element &&
          (import.prefix != null ||
              _visibleUnprefixed(library, name, type.element))) {
        final prefix = _importPrefix(import);
        return '${prefix == null ? '' : '$prefix.'}'
            '$name${!nonNullable && type.nullabilitySuffix == NullabilitySuffix.question ? '?' : ''}';
      }
    }
    invalid(
      'G006',
      'The inferred type $name is hidden in this library. '
          'Write an explicit supported type annotation.',
      field,
    );
  }

  void checkModelNames(List<_Model> models, LibraryElement library) {
    final tables = <String>{};
    final generated = <String>{'generatedModel'};
    for (final model in models) {
      if (!tables.add(_lower(model.table))) {
        error(
          'G007',
          'Duplicate SQL table name ${model.table}.',
          model.element,
        );
      }
      generated.addAll([
        '${model.name}Columns',
        '${model.name}Mapping',
        '${model.name}Relationships',
      ]);
    }
    for (final element in _topLevel(library)) {
      if (_elementPath(element) != output && generated.contains(element.name)) {
        error(
          'G011',
          'Generated identifier ${element.name} already exists.',
          element,
        );
      }
    }
    for (final import in _imports(library)) {
      final prefix = import.prefix?.element;
      if (prefix != null && generated.contains(prefix.name)) {
        error(
          'G011',
          'Generated identifier ${prefix.name} conflicts with an '
              'import prefix.',
          prefix,
        );
      }
    }
  }

  List<_Relationship> relationships(List<_Model> models) {
    final result = <_Relationship>[];
    for (final child in models) {
      final helperNames = <String>{};
      for (final field in child.fields) {
        final annotation = field.reference;
        _Model? parent;
        _Field? target;
        var action = 'noAction';
        if (annotation != null) {
          final type = annotation.getField('target')?.toTypeValue();
          if (type is InterfaceType) {
            parent = models
                .where((model) => model.element == type.element)
                .firstOrNull;
          }
          if (parent == null) {
            error(
              'G012',
              'DbReference target must be a selected model.',
              field.element,
            );
            continue;
          }
          final property = annotation.getField('column')?.toStringValue();
          target = property == null
              ? parent.keys.length == 1
                    ? parent.keys.single
                    : null
              : parent.fields
                    .where((candidate) => candidate.name == property)
                    .firstOrNull;
          final index =
              annotation
                  .getField('onDelete')
                  ?.getField('index')
                  ?.toIntValue() ??
              0;
          const actions = [
            'noAction',
            'restrict',
            'cascade',
            'setNull',
            'setDefault',
          ];
          if (index >= 0 && index < actions.length) action = actions[index];
        } else {
          final candidates = models
              .where(
                (model) =>
                    model != child &&
                    model.keys.length == 1 &&
                    model.keys.single.kind == field.kind &&
                    _lower(field.name) == '${_lower(model.name)}id',
              )
              .toList();
          if (candidates.length == 1) {
            parent = candidates.single;
            target = parent.keys.single;
          }
        }
        if (parent == null) continue;
        if (child.module != null || parent.module != null) {
          error(
            'G013',
            'Virtual tables cannot own or target a foreign key.',
            field.element,
          );
          continue;
        }
        if (target == null ||
            !(parent.keys.length == 1 && target == parent.keys.single ||
                target.unique) ||
            field.kind != target.kind ||
            action == 'setNull' && !field.nullable ||
            action == 'setDefault' &&
                !field.nullable &&
                field.defaultSql == null) {
          error(
            'G012',
            'Foreign keys need a compatible unique target and '
                'valid null/default actions.',
            field.element,
          );
          continue;
        }
        var helper = field.name.endsWith('Id') && field.name.length > 2
            ? field.name.substring(0, field.name.length - 2)
            : field.name;
        if (const {
              'hashCode',
              'runtimeType',
              'toString',
              'noSuchMethod',
            }.contains(helper) ||
            !helperNames.add(helper)) {
          helper = field.name;
          if (!helperNames.add(helper)) {
            error(
              'G012',
              'Relationship helper name is ambiguous.',
              field.element,
            );
            continue;
          }
        }
        result.add(_Relationship(child, parent, field, target, helper, action));
      }
    }
    return result;
  }
}

bool _validSqlName(String value) =>
    value.isNotEmpty && !value.contains('\u0000');

String? _kind(DartType type) {
  if (type is! InterfaceType) return null;
  final uri = _libraryUri(type.element.library);
  if (uri == 'dart:typed_data' && type.element.name == 'Uint8List') {
    return 'blob';
  }
  if (uri != 'dart:core') return null;
  return switch (type.element.name) {
    'BigInt' => 'bigInt',
    'int' => 'integer',
    'double' => 'real',
    'bool' => 'boolean',
    'String' => 'text',
    'DateTime' => 'dateTime',
    _ => null,
  };
}

final class _Field {
  _Field(
    this.element,
    this.kind,
    this.dartType,
    this.keyType, {
    required this.nullable,
    required this.sqlName,
    required this.unique,
    required this.explicitKey,
    required this.generated,
    required this.version,
    required this.json,
    this.keyOrder,
    this.defaultSql,
    this.reference,
  });
  final FieldElement element;
  final String kind, sqlName, dartType, keyType;
  final bool nullable, unique, explicitKey, version, json;
  bool generated;
  int? keyOrder;
  final String? defaultSql;
  final DartObject? reference;
  String get name => element.name!;
  bool get writable => !element.isFinal && element.setter != null;
  String codec(String prefix) => nullable
      ? '${prefix}Codecs.nullable(${prefix}Codecs.$kind)'
      : '${prefix}Codecs.$kind';
}

final class _Model {
  _Model(
    this.element,
    this.table,
    this.fields,
    this.keys,
    this.constructor,
    this.module,
  );
  final ClassElement element;
  final String table;
  final List<_Field> fields, keys;
  final ConstructorElement constructor;
  final String? module;
  String get name => element.name!;
}

final class _Relationship {
  _Relationship(
    this.child,
    this.parent,
    this.field,
    this.target,
    this.helper,
    this.action,
  );
  final _Model child, parent;
  final _Field field, target;
  final String helper, action;
}

String _emit(
  String input,
  String output,
  String prefix,
  String listName,
  List<_Model> models,
  List<_Relationship> relationships,
) {
  final dynamicName = '${listName.substring(0, listName.length - 4)}dynamic';
  final code = StringBuffer(_header)
    ..writeln()
    ..writeln('part of ${_string(_relative(input, p.dirname(output)))};');
  for (final model in models) {
    code.writeln('abstract final class ${model.name}Columns {');
    for (final field in model.fields) {
      code.writeln(
        'static final ${prefix}Column<${model.name}, ${field.dartType}> '
        '${field.name} = ${prefix}Column<${model.name}, ${field.dartType}>('
        'property: ${_string(field.name)}, name: ${_string(field.sqlName)}, '
        'codec: ${field.codec(prefix)}, read: (entity) => entity.${field.name}, '
        '${field.writable ? 'write: (entity, value) => entity.${field.name} = value,' : ''}'
        '${field.keyOrder != null ? 'keyOrder: ${field.keyOrder},' : ''}'
        '${field.generated ? 'generated: true,' : ''}'
        '${field.version ? 'version: true,' : ''}'
        '${field.unique ? 'unique: true,' : ''}'
        '${field.defaultSql != null ? 'defaultSql: ${_string(field.defaultSql!)},' : ''}'
        ');',
      );
    }
    code.writeln(
      'static final $listName<${prefix}Column<${model.name}, $dynamicName>> all = '
      '$listName.unmodifiable([${model.fields.map((field) => field.name).join(',')}]);}',
    );
    code.writeln('abstract final class ${model.name}Mapping {');
    code.writeln(
      'static final ${prefix}EntityType<${model.name}> instance = '
      '${prefix}EntityType<${model.name}>(tableName: ${_string(model.table)},'
      'columns: ${model.name}Columns.all, create: _create,'
      '${model.module == null ? '' : 'virtualModule: ${_string(model.module!)},'}'
      '${model.fields.any((field) => !field.writable) ? 'applyStoreValues: (entity, row) => _create(row),' : ''}'
      ');',
    );
    code.writeln('static ${model.name} _create(${prefix}RowReader row) {');
    final parameters = <String>[];
    for (final parameter in model.constructor.formalParameters) {
      final field = model.fields
          .where((field) => field.name == parameter.name)
          .firstOrNull;
      if (field == null) continue;
      final value = 'row.read(${model.name}Columns.${field.name})';
      parameters.add(parameter.isNamed ? '${parameter.name}: $value' : value);
    }
    code.writeln(
      'final entity = ${model.name}'
      '${_unnamedConstructor(model.constructor) ? '' : '.${model.constructor.name}'}'
      '(${parameters.join(',')});',
    );
    for (final field in model.fields.where((field) => field.writable)) {
      code.writeln(
        'entity.${field.name} = row.read(${model.name}Columns.${field.name});',
      );
    }
    code.writeln('return entity; }');
    code.writeln(
      'static ${prefix}EntityKey key('
      '${[for (var i = 0; i < model.keys.length; i++) '${model.keys[i].keyType} value$i'].join(',')}'
      ') => ${prefix}EntityKey(['
      '${[for (var i = 0; i < model.keys.length; i++) '${model.name}Columns.${model.keys[i].name}.codec.encode(value$i)'].join(',')}'
      ']);}',
    );
    final related = relationships.where((relation) => relation.child == model);
    if (related.isNotEmpty) {
      code.writeln('abstract final class ${model.name}Relationships {');
      for (final relation in related) {
        code.writeln(
          'static final ${prefix}ForeignKey<${model.name}, ${relation.parent.name}> '
          '${relation.helper} = ${prefix}ForeignKey<${model.name}, ${relation.parent.name}>('
          'name: ${_string('${model.name}_${relation.field.name}_${relation.parent.name}')},'
          'child: ${model.name}Mapping.instance, parent: ${relation.parent.name}Mapping.instance,'
          'columns: [${model.name}Columns.${relation.field.name}],'
          'targetColumns: [${relation.parent.name}Columns.${relation.target.name}],'
          'onDelete: ${prefix}ForeignKeyAction.${relation.action},);',
        );
      }
      code.writeln('}');
    }
    code.writeln('final class ${model.name}Fields {');
    code.writeln('${model.name}Fields._();');
    code.writeln('static final instance = ${model.name}Fields._();');
    for (final field in model.fields) {
      code.writeln(
        'final ${field.name} = ${prefix}MappedField(${model.name}Columns.${field.name});',
      );
    }
    final json = model.fields.where((field) => field.json).toList();
    if (json.length == 1) {
      code.writeln(
        '${prefix}JsonPathField<${model.name}> path(String path) => ${json.single.name}.at(path);',
      );
    } else {
      for (final field in json) {
        code.writeln(
          '${prefix}JsonPathField<${model.name}> ${field.name}Path(String path) => ${field.name}.at(path);',
        );
      }
    }
    if (model.module == 'rtree') {
      code.writeln(
        'final bounds = ${prefix}Bounds<${model.name}>('
        'minX: ${model.name}Columns.minX, maxX: ${model.name}Columns.maxX, '
        'minY: ${model.name}Columns.minY, maxY: ${model.name}Columns.maxY,);',
      );
    }
    code.writeln('}');
    code.writeln(
      'extension ${model.name}Query on ${prefix}TypedQuery<${model.name}> {',
    );
    code.writeln(
      '${prefix}TypedQuery<${model.name}> filter(${prefix}SqlPredicate<${model.name}> Function(${model.name}Fields row) build) => where(build(${model.name}Fields.instance));',
    );
    code.writeln(
      '${prefix}TypedQuery<${model.name}> orderByFields($listName<${prefix}SqlOrdering<${model.name}>> Function(${model.name}Fields row) build) => orderBy(build(${model.name}Fields.instance));',
    );
    if (model.module == 'fts5') {
      code.writeln(
        '${prefix}TypedQuery<${model.name}> search(String text) => ${prefix}TypedQuery<${model.name}>(type: type, connection: connection).search(text);',
      );
    }
    code.writeln('}');
  }
  code.writeln(
    'final ${prefix}DbModel generatedModel = ${prefix}DbModel(['
    '${models.map((model) => '${model.name}Mapping.instance').join(',')}],'
    'foreignKeys: ['
    '${relationships.map((relation) => '${relation.child.name}Relationships.${relation.helper}').join(',')}]);',
  );
  return code.toString();
}
