const _ormUri = 'package:sqlite_plus_orm/sqlite_plus_orm.dart';
const _header =
    '// GENERATED CODE - DO NOT MODIFY BY HAND.\n'
    '// Generated by sqlite_plus_generator.\n';

/// Resolve a Dart library and build its ORM part without modifying any files.
///
/// The source must import sqlite_plus_orm and declare the output as a `part`.
/// Annotations are optional: a public concrete class with one conventional `id`
/// or `<ClassName>Id` field is selected by default. [classNames] selects an
/// explicit set instead. Unsupported mappings produce located diagnostics.
Future<GenerationResult> generateLibrary(
  String inputPath, {
  Iterable<String> classNames = const [],
  String? outputPath,
  bool annotatedOnly = false,
}) async {
  final input = p.normalize(p.absolute(inputPath));
  final output = p.normalize(
    p.absolute(
      outputPath ??
          p.join(
            p.dirname(input),
            '${p.basenameWithoutExtension(input)}.orm.g.dart',
          ),
    ),
  );
  if (input == output) {
    _fail('G001', 'Input and output must be different files.', input);
  }
  if (!File(input).existsSync()) {
    _fail('G001', 'Input file does not exist.', input);
  }
  _checkOutputOwnership(output);
  final resolved = await resolveFile(path: input);
  if (resolved is! ResolvedUnitResult) {
    _fail('G001', 'The input could not be resolved as a Dart library.', input);
  }
  final result = resolved;
  if (result.unit.directives.any((directive) => directive is PartOfDirective)) {
    _fail('G002', 'Generate the containing library, not a part file.', input);
  }
  final outputParts = result.unit.directives.whereType<PartDirective>().where(
    (part) =>
        p.normalize(p.join(p.dirname(input), part.uri.stringValue ?? '')) ==
        output,
  );
  if (outputParts.isEmpty) {
    _fail(
      'G002',
      'Add part ${_string(_relative(output, p.dirname(input)))} to the source.',
      input,
    );
  }
  final libraryResult = await result.session.getResolvedLibraryByElement(
    result.libraryElement,
  );
  if (libraryResult is! ResolvedLibraryResult) {
    _fail('G001', 'The containing library could not be resolved.', input);
  }
  final units = {
    for (final unit in libraryResult.units) p.normalize(unit.path): unit,
  };
  final sourceErrors = <GeneratorDiagnostic>[];
  for (final unit in units.values) {
    if (p.normalize(unit.path) == output) continue;
    for (final error in unit.diagnostics) {
      final code = error.diagnosticCode;
      if (code.severity != DiagnosticSeverity.ERROR) continue;
      if (unit.path == input &&
          const {
            'uri_does_not_exist',
            'uri_has_not_been_generated',
            'part_of_different_library',
            'part_of_non_part',
            'part_of_unnamed_library',
          }.contains(code.lowerCaseName) &&
          outputParts.any(
            (part) => error.offset >= part.offset && error.offset < part.end,
          )) {
        continue;
      }
      final location = unit.lineInfo.getLocation(error.offset);
      sourceErrors.add(
        GeneratorDiagnostic(
          'G003',
          error.message,
          unit.path,
          location.lineNumber,
          location.columnNumber,
          offset: error.offset,
        ),
      );
    }
  }
  if (sourceErrors.isNotEmpty) throw GenerationException(sourceErrors);
  final library = result.libraryElement;
  final prefix = _runtimePrefix(library, input);
  final listName = _listName(library, input);
  final inspector = _Inspector(units, output, library);
  final requested = classNames.toSet();
  final classes = library.fragments
      .where((unit) => p.normalize(unit.source.fullName) != output)
      .expand((unit) => unit.classes)
      .map((fragment) => fragment.element)
      .toList();
  final selected = <ClassElement>[];
  for (final element in classes) {
    final explicitlySelected = requested.contains(element.name);
    if (explicitlySelected ||
        requested.isEmpty &&
            !element.isPrivate &&
            (_annotation(element, 'DbEntity') != null ||
                !annotatedOnly &&
                    !element.isAbstract &&
                    _conventionalKeys(element).isNotEmpty)) {
      selected.add(element);
    }
  }
  for (final missing in requested.difference(
    classes.map((element) => element.name).whereType<String>().toSet(),
  )) {
    inspector.error('G004', 'No class named $missing exists in this library.');
  }
  if (selected.isEmpty && inspector.diagnostics.isEmpty) {
    inspector.error(
      'G004',
      'No models selected. Add a conventional id, @DbEntity, or --class.',
    );
  }
  final models = <_Model>[];
  for (final element in selected) {
    try {
      models.add(inspector.inspect(element));
    } on _InvalidModel {
      // Retain one actionable mapping diagnostic per invalid model.
    }
  }
  inspector.checkModelNames(models, library);
  final relationships = inspector.relationships(models);
  if (inspector.diagnostics.isNotEmpty) {
    throw GenerationException(inspector.diagnostics);
  }
  _requireRuntimeNames(library, prefix, [
    if (models.any((model) => model.fields.any((field) => field.json)))
      'JsonPathField',
    if (models.any((model) => model.fields.any((field) => field.document)))
      'DocumentField',
    if (models.any((model) => model.module == 'rtree')) 'Bounds',
    if (models.any((model) => model.scalars.isNotEmpty)) ...[
      'EntityScalar',
      'SqlCall',
      'SqlArgument',
    ],
  ], input);
  final emitted = _emit(
    input,
    output,
    prefix,
    listName,
    models,
    relationships,
    annotatedOnly: annotatedOnly,
    classNames: requested,
  );
  return GenerationResult(
    input,
    output,
    await _format(emitted, output),
    models.map((model) => model.name),
  );
}

/// Formats with the same `dart format` the repository check runs.
Future<String> _format(String source, String outputPath) async {
  var anchor = Directory(p.dirname(outputPath));
  while (!anchor.existsSync()) {
    final parent = anchor.parent;
    if (parent.path == anchor.path) {
      anchor = Directory.systemTemp;
      break;
    }
    anchor = parent;
  }
  final directory = await anchor.createTemp('.sqlite-plus-format-');
  final file = File(p.join(directory.path, 'part.dart'));
  try {
    await file.writeAsString(source);
    final result = await Process.run(Platform.resolvedExecutable, [
      'format',
      file.path,
    ]);
    if (result.exitCode != 0) {
      throw StateError('dart format failed: ${result.stderr}');
    }
    return await file.readAsString();
  } finally {
    await directory.delete(recursive: true);
  }
}

/// Write a validated generated part atomically, or compare it in [check] mode.
///
/// Returns false only when [check] finds a missing or stale output. Existing
/// hand-written files, directories and symbolic links are never overwritten.
Future<bool> writeGenerated(
  GenerationResult result, {
  bool check = false,
}) async {
  _checkOutputOwnership(result.outputPath);
  final output = File(result.outputPath);
  final current = output.existsSync()
      ? utf8.decode(output.readAsBytesSync(), allowMalformed: true)
      : null;
  if (current == result.code) return true;
  if (check) return false;
  await output.parent.create(recursive: true);
  final temporaryDirectory = await output.parent.createTemp(
    '.sqlite-plus-generator-',
  );
  final temporary = File(p.join(temporaryDirectory.path, 'output.dart'));
  try {
    await temporary.writeAsString(result.code, flush: true);
    // Recheck after the asynchronous write, before replacing the destination.
    _checkOutputOwnership(result.outputPath);
    await temporary.rename(output.path);
  } finally {
    await temporaryDirectory.delete(recursive: true);
  }
  return true;
}

/// One package scan: a part for every library that declares `@DbEntity`.
final class PackageGeneration {
  PackageGeneration(this.libraries, this.migrations);

  /// Parts for libraries that contain a public `@DbEntity` class.
  final List<GenerationResult> libraries;

  /// The package `generatedModel` used by `migrations.ensureCreated`.
  final GenerationResult migrations;
}

/// Scans `lib/` under [packageRoot] for public `@DbEntity` classes.
///
/// A library with no `@DbEntity` class is left unchanged, including a class
/// whose only claim is a conventional `id`. Each selected library receives
/// `part '<name>.orm.g.dart';` when that directive is missing. [classNames]
/// limits the scan to those classes.
Future<PackageGeneration> generatePackage(
  String packageRoot, {
  Iterable<String> classNames = const [],
  bool ensurePart = true,
  void Function(String message)? report,
}) async {
  final root = p.normalize(p.absolute(packageRoot));
  final lib = Directory(p.join(root, 'lib'));
  if (!File(p.join(root, 'pubspec.yaml')).existsSync() || !lib.existsSync()) {
    _fail(
      'G001',
      'Run from a package root that contains pubspec.yaml and lib/.',
      root,
    );
  }
  final requested = classNames.toSet();
  final sources =
      lib
          .listSync(recursive: true)
          .whereType<File>()
          .where((file) => file.path.endsWith('.dart'))
          .map((file) => p.normalize(file.path))
          .where((path) => !_isGeneratedDart(path))
          .toList()
        ..sort();
  final libraries = <GenerationResult>[];
  final found = <String>{};
  for (final source in sources) {
    final shown = _display(source, root);
    if (requested.isEmpty) {
      final existing = currentGeneration(source, annotatedOnly: true);
      if (existing != null) {
        found.addAll(existing.entityNames);
        libraries.add(existing);
        report?.call(
          'Found ${existing.entityNames.join(', ')} in $shown. '
          'Already generated. Leaving ${_display(existing.outputPath, root)} '
          'unchanged.',
        );
        continue;
      }
    }
    if (!_mentionsDbEntity(source)) continue;
    report?.call('Reading $shown.');
    final names = await _publicDbEntityNames(source, requested);
    if (names.isEmpty) {
      report?.call('No selected public @DbEntity in $shown.');
      continue;
    }
    found.addAll(names);
    report?.call('Found ${names.join(', ')} in $shown.');
    if (ensurePart) await _ensurePartDirective(source);
    final output = p.join(
      p.dirname(source),
      '${p.basenameWithoutExtension(source)}.orm.g.dart',
    );
    report?.call('Generating ${_display(output, root)}.');
    libraries.add(
      await generateLibrary(
        source,
        classNames: requested.isEmpty ? const [] : names,
        annotatedOnly: true,
      ),
    );
  }
  final missing = requested.difference(found);
  if (missing.isNotEmpty) {
    _fail(
      'G004',
      'No public @DbEntity class named ${missing.join(', ')} exists under lib/.',
      lib.path,
    );
  }
  if (libraries.isEmpty) {
    _fail(
      'G004',
      'No public @DbEntity classes were found under lib/.',
      lib.path,
    );
  }
  final migrationsPath = p.join(lib.path, 'sqlite_plus_migrations.g.dart');
  final shownMigrations = _display(migrationsPath, root);
  final migrations =
      _reusableMigrations(root, migrationsPath, libraries) ??
      GenerationResult(
        root,
        migrationsPath,
        await _format(_migrationSource(lib.path, libraries), migrationsPath),
        libraries.expand((library) => library.entityNames),
      );
  report?.call(
    migrations.reused
        ? 'Already generated. Leaving $shownMigrations unchanged.'
        : 'Preparing $shownMigrations.',
  );
  return PackageGeneration(libraries, migrations);
}

/// Writes [generated] or compares it when [check] is set.
///
/// Returns false when [check] finds a missing or stale part. Pass
/// `ensurePart: false` to [generatePackage] when checking, so a missing `part`
/// directive stays a generation error instead of an edit.
Future<bool> writePackage(
  PackageGeneration generated, {
  bool check = false,
}) async {
  var current = true;
  for (final library in generated.libraries) {
    current = await writeGenerated(library, check: check) && current;
  }
  return await writeGenerated(generated.migrations, check: check) && current;
}

bool _isGeneratedDart(String path) {
  final name = p.basename(path);
  return name.endsWith('.orm.g.dart') ||
      name == 'sqlite_plus_migrations.g.dart';
}

Future<List<String>> _publicDbEntityNames(
  String input,
  Set<String> requested,
) async {
  if (!File(input).existsSync()) return const [];
  final resolved = await resolveFile(path: input);
  if (resolved is! ResolvedUnitResult ||
      resolved.unit.directives.any(
        (directive) => directive is PartOfDirective,
      )) {
    return const [];
  }
  final names = <String>[];
  for (final fragment in resolved.libraryElement.fragments) {
    for (final element in fragment.classes) {
      final type = element.element;
      final name = type.name;
      if (name == null ||
          type.isPrivate ||
          _annotation(type, 'DbEntity') == null) {
        continue;
      }
      if (requested.isEmpty || requested.contains(name)) names.add(name);
    }
  }
  return names;
}

Future<void> _ensurePartDirective(String input) async {
  final partUri = '${p.basenameWithoutExtension(input)}.orm.g.dart';
  final file = File(input);
  final source = await file.readAsString();
  final unit = parseString(content: source, path: input).unit;
  final present = unit.directives.whereType<PartDirective>().any(
    (directive) => directive.uri.stringValue == partUri,
  );
  if (present) return;
  final at = unit.directives.isEmpty ? 0 : unit.directives.last.end;
  final before = source.substring(0, at);
  var after = source.substring(at);
  if (after.startsWith('\n')) after = after.substring(1);
  final gap = before.isEmpty || before.endsWith('\n') ? '' : '\n';
  final literal = partUri.contains("'") ? _string(partUri) : "'$partUri'";
  await file.writeAsString('$before$gap\npart $literal;\n$after');
}

String _migrationSource(String libPath, List<GenerationResult> libraries) {
  final imports = <String>[];
  final entities = <String>[];
  final foreignKeys = <String>[];
  final names = <String>[];
  final used = <String>{};
  for (final library in libraries) {
    final relative = _relative(library.inputPath, libPath);
    var alias = _libraryAlias(relative);
    var suffix = 2;
    while (!used.add(alias)) {
      alias = '${_libraryAlias(relative)}_$suffix';
      suffix++;
    }
    imports.add("import ${_string(relative)} as $alias;");
    entities.add('...$alias.generatedModel.entities');
    foreignKeys.add('...$alias.generatedModel.foreignKeys');
    names.addAll(library.entityNames);
  }
  return '$_header'
      '${_stampLine(_migrationDigest(libPath, libraries), names)}\n'
      'import \'package:sqlite_plus_orm/sqlite_plus_orm.dart\';\n'
      '${imports.join('\n')}\n\n'
      'final DbModel generatedModel = DbModel([\n'
      '${entities.join(',\n')},\n'
      '], foreignKeys: [\n'
      '${foreignKeys.join(',\n')},\n'
      ']);\n';
}

/// Returns the existing part when its source stamp still matches.
///
/// This does not resolve the library. A missing stamp, a changed source, a
/// different class selection, or a damaged part returns null so generation runs.
GenerationResult? currentGeneration(
  String inputPath, {
  String? outputPath,
  Iterable<String> classNames = const [],
  bool annotatedOnly = false,
}) {
  final input = p.normalize(p.absolute(inputPath));
  if (!File(input).existsSync()) return null;
  final output = p.normalize(
    p.absolute(
      outputPath ??
          p.join(
            p.dirname(input),
            '${p.basenameWithoutExtension(input)}.orm.g.dart',
          ),
    ),
  );
  return _reusablePart(
    input,
    output,
    annotatedOnly: annotatedOnly,
    classNames: classNames,
  );
}

GenerationResult? _reusablePart(
  String input,
  String output, {
  required bool annotatedOnly,
  required Iterable<String> classNames,
}) {
  final code = _ownedGenerated(output);
  if (code == null) return null;
  final partOf = 'part of ${_string(_relative(input, p.dirname(output)))};';
  if (!code.contains(partOf) || !code.contains('generatedModel')) return null;
  final parsed = _stamp(code);
  if (parsed == null) return null;
  final digest = _sourceDigest(
    input,
    annotatedOnly: annotatedOnly,
    classNames: classNames,
  );
  if (parsed.digest != digest) return null;
  return GenerationResult(input, output, code, parsed.entities, reused: true);
}

GenerationResult? _reusableMigrations(
  String packageRoot,
  String output,
  List<GenerationResult> libraries,
) {
  final code = _ownedGenerated(output);
  if (code == null || !code.contains('final DbModel generatedModel')) {
    return null;
  }
  final parsed = _stamp(code);
  if (parsed == null) return null;
  if (parsed.digest !=
      _migrationDigest(p.join(packageRoot, 'lib'), libraries)) {
    return null;
  }
  return GenerationResult(
    packageRoot,
    output,
    code,
    libraries.expand((library) => library.entityNames),
    reused: true,
  );
}

String? _ownedGenerated(String output) {
  final kind = FileSystemEntity.typeSync(output, followLinks: false);
  if (kind != FileSystemEntityType.file) return null;
  final code = utf8.decode(
    File(output).readAsBytesSync(),
    allowMalformed: true,
  );
  if (!code.startsWith(_header)) return null;
  return code;
}

({String digest, List<String> entities})? _stamp(String code) {
  final match = RegExp(
    r'^// Source-sha256: ([0-9a-f]{64}) entities: (\S+)$',
    multiLine: true,
  ).firstMatch(code);
  if (match == null) return null;
  return (digest: match.group(1)!, entities: match.group(2)!.split(','));
}

String _stampLine(String digest, Iterable<String> entities) =>
    '// Source-sha256: $digest entities: ${entities.join(',')}';

String _sourceDigest(
  String input, {
  required bool annotatedOnly,
  required Iterable<String> classNames,
}) {
  final bytes = BytesBuilder(copy: false);
  final names = classNames.toList()..sort();
  bytes.add(utf8.encode(annotatedOnly ? 'entity' : 'library'));
  bytes.addByte(0);
  bytes.add(utf8.encode(names.join(',')));
  bytes.addByte(0);
  for (final path in _stampFiles(input)) {
    bytes.add(utf8.encode(_relative(path, p.dirname(input))));
    bytes.addByte(0);
    bytes.add(File(path).readAsBytesSync());
    bytes.addByte(0);
  }
  return sha256.convert(bytes.takeBytes()).toString();
}

String _migrationDigest(String libPath, List<GenerationResult> libraries) {
  final buffer = StringBuffer();
  for (final library in libraries) {
    buffer
      ..writeln(_relative(library.inputPath, libPath))
      ..writeln(_stamp(library.code)?.digest ?? '');
  }
  return sha256.convert(utf8.encode(buffer.toString())).toString();
}

List<String> _stampFiles(String input) {
  final source = File(input).readAsStringSync();
  final files = <String>[input];
  try {
    final unit = parseString(content: source, path: input).unit;
    for (final part in unit.directives.whereType<PartDirective>()) {
      final uri = part.uri.stringValue;
      if (uri == null) continue;
      final path = p.normalize(p.join(p.dirname(input), uri));
      if (path == input || _isGeneratedDart(path) || !File(path).existsSync()) {
        continue;
      }
      files.add(path);
    }
  } catch (_) {
    // A source that does not parse is generated through the normal diagnostic.
  }
  files.sort();
  return files;
}

bool _mentionsDbEntity(String path) {
  try {
    return File(path).readAsStringSync().contains('DbEntity');
  } on FileSystemException {
    return false;
  }
}

String _display(String path, String from) => p
    .relative(p.normalize(path), from: p.normalize(from))
    .replaceAll('\\', '/');

String _libraryAlias(String relative) {
  final withoutExtension = relative.endsWith('.dart')
      ? relative.substring(0, relative.length - 5)
      : relative;
  final alias = withoutExtension.replaceAll(RegExp('[^A-Za-z0-9]'), '_');
  return RegExp('^[0-9]').hasMatch(alias) ? 'library_$alias' : alias;
}

void _checkOutputOwnership(String output) {
  final kind = FileSystemEntity.typeSync(output, followLinks: false);
  if (kind == FileSystemEntityType.notFound) return;
  if (kind != FileSystemEntityType.file) {
    _fail('G020', 'Output must be an ordinary generated file.', output);
  }
  final contents = File(output).readAsBytesSync();
  final signature = _header.codeUnits;
  if (contents.length < signature.length ||
      List.generate(
        signature.length,
        (index) => index,
      ).any((index) => contents[index] != signature[index])) {
    _fail(
      'G020',
      'Refusing to replace a file without the generator header.',
      output,
    );
  }
}

Never _fail(String code, String message, String path) =>
    throw GenerationException([GeneratorDiagnostic(code, message, path, 1, 1)]);

String _relative(String path, String from) =>
    p.relative(path, from: from).replaceAll('\\', '/');

String _string(String value) => jsonEncode(value).replaceAll(r'$', r'\$');

String _lower(String value) =>
    value.replaceAllMapped(RegExp('[A-Z]'), (match) => match[0]!.toLowerCase());

String _libraryUri(LibraryElement library) =>
    library.firstFragment.source.uri.toString();

String _elementPath(Element element) =>
    element.firstFragment.libraryFragment?.source.fullName ?? '';

int _nameOffset(Element element) => element.firstFragment.nameOffset ?? 0;

bool _unnamedConstructor(ConstructorElement constructor) =>
    constructor.name == null || constructor.name == 'new';

List<LibraryImport> _imports(LibraryElement library) =>
    library.firstFragment.libraryImports;

bool _importDeferred(LibraryImport import) =>
    import.prefix?.isDeferred ?? false;

String? _importPrefix(LibraryImport import) => import.prefix?.name;

Element? _importLookup(LibraryImport import, String name) {
  final prefix = _importPrefix(import);
  return import.namespace.get2(prefix == null ? name : '$prefix.$name');
}

Iterable<Element> _topLevel(LibraryElement library) => [
  ...library.classes,
  ...library.enums,
  ...library.mixins,
  ...library.extensions,
  ...library.extensionTypes,
  ...library.topLevelFunctions,
  ...library.topLevelVariables,
  ...library.typeAliases,
  ...library.getters,
  ...library.setters,
];

DartObject? _annotation(Element element, String name) {
  for (final annotation in element.metadata.annotations) {
    final value = annotation.computeConstantValue();
    final type = value?.type;
    if (type is InterfaceType &&
        type.element.name == name &&
        _libraryUri(type.element.library) == _ormUri) {
      return value;
    }
  }
  return null;
}

List<FieldElement> _fields(ClassElement element) => element.fields
    .where(
      (field) =>
          field.name != null &&
          !field.isStatic &&
          !field.isPrivate &&
          !field.isOriginGetterSetter &&
          !field.isOriginEnumValues &&
          _annotation(field, 'DbIgnore') == null,
    )
    .toList();

List<FieldElement> _conventionalKeys(ClassElement element) => _fields(element)
    .where(
      (field) =>
          _lower(field.name!) == 'id' ||
          _lower(field.name!) == '${_lower(element.name!)}id',
    )
    .toList();

String _runtimePrefix(LibraryElement library, String input) {
  const names = [
    'Column',
    'EntityType',
    'RowReader',
    'Codecs',
    'EntityKey',
    'DbModel',
    'ForeignKey',
    'ForeignKeyAction',
    'MappedField',
    'SqlPredicate',
    'TypedQuery',
    'SqlOrdering',
  ];
  final imports = [..._imports(library)]
    ..sort(
      (a, b) => (a.prefix == null ? 1 : 0).compareTo(b.prefix == null ? 1 : 0),
    );
  for (final import in imports) {
    if (_importDeferred(import)) continue;
    if (import.prefix == null &&
        _topLevel(library).any(
          (element) =>
              names.contains(element.name) &&
              (element.library == null ||
                  _libraryUri(element.library!) != _ormUri),
        )) {
      continue;
    }
    if (names.every((name) {
      final element = _importLookup(import, name);
      return element is InterfaceElement &&
          _libraryUri(element.library) == _ormUri &&
          (import.prefix != null || _visibleUnprefixed(library, name, element));
    })) {
      final prefix = _importPrefix(import);
      return prefix == null ? '' : '$prefix.';
    }
  }
  _fail(
    'G002',
    'Import the public sqlite_plus_orm runtime eagerly without hiding its '
        'metadata types (an import prefix is supported).',
    input,
  );
}

String _listName(LibraryElement library, String input) {
  for (final import in _imports(library)) {
    if (_importDeferred(import)) continue;
    final prefix = _importPrefix(import);
    final name = prefix == null ? 'List' : '$prefix.List';
    final element = _importLookup(import, 'List');
    if (element is InterfaceElement &&
        _libraryUri(element.library) == 'dart:core' &&
        (prefix != null || _visibleUnprefixed(library, 'List', element))) {
      return name;
    }
  }
  _fail(
    'G011',
    'The core List type is hidden. Import dart:core with a prefix '
        'or use manual metadata.',
    input,
  );
}

void _requireRuntimeNames(
  LibraryElement library,
  String prefix,
  List<String> names,
  String input,
) {
  for (final name in names) {
    var found = false;
    for (final import in _imports(library)) {
      if (_importDeferred(import)) continue;
      final importPrefix = _importPrefix(import);
      final qualified = importPrefix == null ? '' : '$importPrefix.';
      if (qualified != prefix) continue;
      final element = _importLookup(import, name);
      if (element is InterfaceElement &&
          _libraryUri(element.library) == _ormUri) {
        found = true;
        break;
      }
    }
    if (!found) {
      _fail(
        'G002',
        'Import $name from sqlite_plus_orm. The generated mapping uses it.',
        input,
      );
    }
  }
}

bool _visibleUnprefixed(
  LibraryElement library,
  String name,
  Element expected,
) =>
    !_topLevel(library).any((element) => element.name == name) &&
    _imports(library).where((import) => import.prefix == null).every((import) {
      final element = _importLookup(import, name);
      return element == null || element == expected;
    });

final class _InvalidModel implements Exception {}

final class _Inspector {
  _Inspector(this.units, this.output, this.library);
  final Map<String, ResolvedUnitResult> units;
  final String output;
  final LibraryElement library;
  final List<GeneratorDiagnostic> diagnostics = [];
  final Set<String> scalarNames = {};

  void error(String code, String message, [Element? element]) {
    final path = element == null ? units.keys.first : _elementPath(element);
    final resolvedPath = path.isEmpty ? units.keys.first : path;
    final unit = units[p.normalize(resolvedPath)];
    final offset = element == null ? 0 : _nameOffset(element);
    final location = unit?.lineInfo.getLocation(offset);
    diagnostics.add(
      GeneratorDiagnostic(
        code,
        message,
        resolvedPath,
        location?.lineNumber ?? 1,
        location?.columnNumber ?? 1,
        offset: offset,
      ),
    );
  }

  Never invalid(String code, String message, Element element) {
    error(code, message, element);
    throw _InvalidModel();
  }

  _Model inspect(ClassElement element) {
    if (element.isPrivate ||
        element.isAbstract ||
        element.typeParameters.isNotEmpty ||
        element.mixins.isNotEmpty ||
        (element.supertype?.element.name != 'Object' ||
            _libraryUri(element.supertype!.element.library) != 'dart:core')) {
      invalid(
        'G005',
        'Models must be public concrete nongeneric classes '
            'without inherited or mixed-in storage.',
        element,
      );
    }
    final columns = <_Field>[];
    for (final field in _fields(element)) {
      final document = _annotation(field, 'DbDocument') != null;
      final json = _annotation(field, 'DbJson') != null;
      final vector = _annotation(field, 'DbVector');
      var kind = _kind(field.type);
      String? documentFromJson;
      int? vectorDimensions;
      String? vectorMetric;
      if (document && json) {
        invalid(
          'G013',
          '@DbDocument and @DbJson mark different columns. '
              'A String column uses @DbJson.',
          field,
        );
      }
      if (document && vector != null) {
        invalid(
          'G013',
          '@DbDocument and @DbVector mark different columns.',
          field,
        );
      }
      if (document) {
        if (kind == 'text') {
          invalid(
            'G013',
            '@DbDocument stores an object. A String column uses @DbJson.',
            field,
          );
        }
        if (kind != null) {
          invalid(
            'G013',
            '@DbDocument stores an object with fromJson and toJson.',
            field,
          );
        }
        documentFromJson = _documentFromJson(field);
        kind = 'document';
      }
      if (vector != null) {
        if (!_isDoubleList(field.type)) {
          invalid('G013', '@DbVector needs a List<double> column.', field);
        }
        vectorDimensions = vector.getField('dimensions')?.toIntValue();
        vectorMetric = vector.getField('metric')?.toStringValue();
        if (vectorDimensions == null ||
            vectorDimensions < 1 ||
            vectorDimensions > 4096 ||
            vectorMetric == null ||
            !_identifier(vectorMetric)) {
          invalid(
            'G013',
            '@DbVector dimensions must be 1 to 4096 and metric must be an identifier.',
            field,
          );
        }
        kind = 'vector';
      }
      if (kind == null) {
        invalid(
          'G006',
          'Unsupported persisted type '
              '${field.type.getDisplayString()}. '
              'Use explicit manual metadata for custom codecs.',
          field,
        );
      }
      final column = _annotation(field, 'DbColumn');
      final key = _annotation(field, 'DbKey');
      final name = column?.getField('name')?.toStringValue() ?? field.name!;
      if (!_validSqlName(name)) {
        invalid(
          'G007',
          'SQL column names must be nonempty and contain no NUL.',
          field,
        );
      }
      if (const {
        'all',
        'hashCode',
        'runtimeType',
        'toString',
        'noSuchMethod',
      }.contains(field.name)) {
        invalid(
          'G011',
          'The property ${field.name} conflicts with a generated helper. '
              'Use manual metadata for this property.',
          field,
        );
      }
      final defaultSql = column?.getField('defaultSql')?.toStringValue();
      if (defaultSql != null &&
          (defaultSql.trim().isEmpty || defaultSql.contains('\u0000'))) {
        invalid(
          'G007',
          'Default SQL must be nonempty and contain no NUL.',
          field,
        );
      }
      columns.add(
        _Field(
          field,
          kind,
          sourceType(field),
          sourceType(field, canonical: true, nonNullable: true),
          nullable: field.type.nullabilitySuffix == NullabilitySuffix.question,
          sqlName: name,
          defaultSql: defaultSql,
          unique: column?.getField('unique')?.toBoolValue() ?? false,
          keyOrder: key?.getField('order')?.toIntValue(),
          generated: key?.getField('generated')?.toBoolValue() ?? false,
          explicitKey: key != null,
          version: _annotation(field, 'DbVersion') != null,
          json: json,
          documentFromJson: documentFromJson,
          reference: _annotation(field, 'DbReference'),
          vectorDimensions: vectorDimensions,
          vectorMetric: vectorMetric,
        ),
      );
    }
    final names = <String>{};
    for (final field in columns) {
      if (!names.add(_lower(field.sqlName))) {
        invalid(
          'G007',
          'Duplicate SQL column name ${field.sqlName}.',
          field.element,
        );
      }
    }
    final explicitKeys = columns.where((field) => field.explicitKey).toList();
    if (explicitKeys.isEmpty) {
      final conventional = _conventionalKeys(element);
      if (conventional.length != 1) {
        invalid(
          'G008',
          'A model needs exactly one conventional id/ClassNameId '
              'or explicit ordered @DbKey annotations.',
          element,
        );
      }
      final key = columns.firstWhere(
        (field) => field.element == conventional.single,
      );
      key.keyOrder = 0;
      key.generated = key.nullable && ['bigInt', 'integer'].contains(key.kind);
    }
    final keys = columns.where((field) => field.keyOrder != null).toList()
      ..sort((a, b) => a.keyOrder!.compareTo(b.keyOrder!));
    for (var i = 0; i < keys.length; i++) {
      if (keys[i].keyOrder != i) {
        invalid(
          'G008',
          'Key orders must be unique and consecutive from zero.',
          keys[i].element,
        );
      }
    }
    for (final field in columns) {
      if (field.document && field.version) {
        invalid(
          'G013',
          '@DbDocument cannot be the version column.',
          field.element,
        );
      }
      if (field.generated &&
          (keys.length != 1 ||
              field.keyOrder != 0 ||
              !field.nullable ||
              !['bigInt', 'integer'].contains(field.kind))) {
        invalid(
          'G009',
          'Only one nullable int/BigInt primary key can be generated.',
          field.element,
        );
      }
      if (field.version &&
          (field.nullable ||
              field.keyOrder != null ||
              !['bigInt', 'integer'].contains(field.kind))) {
        invalid(
          'G009',
          'A version must be a nonnullable int/BigInt non-key field.',
          field.element,
        );
      }
    }
    if (columns.where((field) => field.version).length > 1) {
      invalid('G009', 'A model can have only one version field.', element);
    }
    final entity = _annotation(element, 'DbEntity');
    final module = entity?.getField('module')?.toStringValue();
    final tokenizer = entity?.getField('tokenizer')?.toStringValue();
    _checkVirtual(element, columns, module, tokenizer);
    final constructors = element.constructors
        .where((ctor) => !ctor.isFactory)
        .toList();
    bool usable(ConstructorElement ctor) {
      var unmappedPositional = false;
      for (final parameter in ctor.formalParameters.where(
        (parameter) => parameter.isPositional,
      )) {
        if (columns.any((field) => field.name == parameter.name)) {
          if (unmappedPositional) return false;
        } else {
          unmappedPositional = true;
        }
      }
      final mapped = ctor.formalParameters.map((param) => param.name).toSet();
      return ctor.formalParameters.every(
            (param) =>
                !param.isRequiredNamed && !param.isRequiredPositional ||
                columns.any((field) => field.name == param.name),
          ) &&
          ctor.formalParameters.every((param) {
            final field = columns
                .where((field) => field.name == param.name)
                .firstOrNull;
            return field == null ||
                units.values.first.typeSystem.isAssignableTo(
                  field.element.type,
                  param.type,
                );
          }) &&
          columns.every(
            (field) =>
                field.writable ||
                mapped.contains(field.name) &&
                    directlyInitializes(ctor, field.element),
          );
    }

    final candidates = constructors.where(usable).toList();
    final unnamed = candidates.where(_unnamedConstructor).toList();
    final constructor = unnamed.isNotEmpty
        ? unnamed.single
        : candidates.length == 1
        ? candidates.single
        : null;
    if (constructor == null) {
      invalid(
        'G010',
        'No unambiguous generative constructor maps every required '
            'parameter and final persisted field.',
        element,
      );
    }
    final table =
        _annotation(element, 'DbEntity')?.getField('table')?.toStringValue() ??
        element.name!;
    if (!_validSqlName(table) || _lower(table).startsWith('sqlite_')) {
      invalid(
        'G007',
        'Table names must be nonempty, contain no NUL and avoid sqlite_.',
        element,
      );
    }
    final scalars = _scalars(element, columns, table, module);
    return _Model(
      element,
      table,
      columns,
      keys,
      constructor,
      module,
      tokenizer,
      scalars,
    );
  }

  List<_Scalar> _scalars(
    ClassElement element,
    List<_Field> columns,
    String table,
    String? module,
  ) {
    final executables = <ExecutableElement>[
      ...element.methods,
      ...element.getters.where((getter) => getter.isOriginDeclaration),
    ];
    final taken = columns.map((field) => field.name).toSet();
    final json = columns.where((field) => field.json).toList();
    if (json.length == 1) taken.add('path');
    if (json.length > 1) {
      taken.addAll(json.map((field) => '${field.name}Path'));
    }
    if (module == 'rtree') taken.add('bounds');
    final scalars = <_Scalar>[];
    for (final executable in executables) {
      if (_annotation(executable, 'DbScalar') == null) continue;
      final name = executable.name;
      if (name == null || name.isEmpty) {
        invalid('G014', '@DbScalar needs a name.', executable);
      }
      if (executable.isStatic || executable.formalParameters.isNotEmpty) {
        invalid(
          'G014',
          '@DbScalar $name() reads mapped fields. It takes no parameters.',
          executable,
        );
      }
      final declaration = _methodDeclaration(executable);
      if (declaration == null) {
        invalid(
          'G014',
          '@DbScalar $name() has no resolvable body.',
          executable,
        );
      }
      if (declaration.body.isAsynchronous || declaration.body.isGenerator) {
        invalid(
          'G014',
          '@DbScalar $name() is a synchronous function of the row.',
          executable,
        );
      }
      if (!_scalarReturnAllowed(executable.returnType)) {
        invalid(
          'G014',
          '@DbScalar $name() must return null or a mapped SQL value.',
          executable,
        );
      }
      if (taken.contains(name)) {
        invalid(
          'G014',
          'The scalar $name conflicts with a mapped field or query helper.',
          executable,
        );
      }
      taken.add(name);
      final visitor = _ScalarReads(element, columns);
      declaration.body.accept(visitor);
      if (visitor.failure != null) {
        invalid('G014', visitor.failure!, executable);
      }
      final reads = columns
          .where((field) => visitor.reads.contains(field.element))
          .toList();
      final sqlName = _uniqueScalarName(_scalarSqlName(table, name));
      final returnType = executable.returnType.getDisplayString();
      scalars.add(
        _Scalar(
          executable,
          name,
          sqlName,
          reads,
          returnType,
          declaration.isGetter,
        ),
      );
    }
    return scalars;
  }

  MethodDeclaration? _methodDeclaration(ExecutableElement element) {
    final path = p.normalize(
      element.firstFragment.libraryFragment.source.fullName,
    );
    final unit = units[path];
    if (unit == null) return null;
    for (final declaration
        in unit.unit.declarations.whereType<ClassDeclaration>()) {
      for (final member
          in declaration.body.members.whereType<MethodDeclaration>()) {
        if (member.declaredFragment?.element == element) return member;
      }
    }
    return null;
  }

  bool _scalarReturnAllowed(DartType type) {
    if (type is DynamicType || type.isDartCoreObject) return true;
    if (type is VoidType || type is NeverType || type is RecordType) {
      return false;
    }
    if (type is InterfaceType &&
        (type.isDartAsyncFuture || type.isDartAsyncFutureOr)) {
      return false;
    }
    return _kind(type) != null;
  }

  String _uniqueScalarName(String base) {
    var name = base;
    var suffix = 2;
    while (!scalarNames.add(name)) {
      name = '${base}_$suffix';
      suffix++;
    }
    return name;
  }

  String _documentFromJson(FieldElement field) {
    final type = field.type;
    if (type is! InterfaceType || type.element is! ClassElement) {
      invalid(
        'G013',
        '@DbDocument needs a class with fromJson and toJson.',
        field,
      );
    }
    final owner = type.element as ClassElement;
    final factory = owner.constructors
        .where(
          (constructor) =>
              constructor.isFactory && constructor.name == 'fromJson',
        )
        .toList();
    final methods = owner.methods
        .where((method) => method.isStatic && method.name == 'fromJson')
        .toList();
    if (factory.isNotEmpty && methods.isNotEmpty) {
      invalid(
        'G013',
        '${owner.name} has both a factory and a static fromJson. Keep one.',
        field,
      );
    }
    if (factory.length > 1 || methods.length > 1) {
      invalid(
        'G013',
        '${owner.name}.fromJson is declared more than once.',
        field,
      );
    }
    final fromJson = factory.singleOrNull ?? methods.singleOrNull;
    if (fromJson == null) {
      invalid(
        'G013',
        '${owner.name} needs fromJson(Map<String, Object?> json) or '
            'fromJson(Map<String, dynamic> json).',
        field,
      );
    }
    final parameters = fromJson.formalParameters;
    if (parameters.length != 1 || parameters.single.isNamed) {
      invalid(
        'G013',
        '${owner.name}.fromJson must take one map parameter.',
        field,
      );
    }
    final mapKind = _jsonMapKind(parameters.single.type);
    if (mapKind == null) {
      invalid(
        'G013',
        '${owner.name}.fromJson must take Map<String, Object?> or '
            'Map<String, dynamic>.',
        field,
      );
    }
    final toJson = _documentToJson(owner);
    if (toJson == null) {
      invalid(
        'G013',
        '${owner.name} needs a toJson() method that returns a Map.',
        field,
      );
    }
    if (toJson.formalParameters.any((parameter) => parameter.isRequired)) {
      invalid('G013', '${owner.name}.toJson() must take no arguments.', field);
    }
    if (!_returnsJsonMap(toJson.returnType)) {
      invalid('G013', '${owner.name}.toJson() must return a Map.', field);
    }
    final written = sourceType(field);
    final typeName = written.endsWith('?')
        ? written.substring(0, written.length - 1)
        : written;
    if (mapKind == 'dynamic') {
      return '(Map<String, Object?> json) => '
          '$typeName.fromJson(Map<String, dynamic>.from(json))';
    }
    return '$typeName.fromJson';
  }

  MethodElement? _documentToJson(ClassElement owner) {
    final declared = owner.methods.where(
      (method) =>
          !method.isStatic &&
          method.name == 'toJson' &&
          method.enclosingElement == owner,
    );
    if (declared.isNotEmpty) return declared.first;
    final parent = owner.supertype?.element;
    if (parent is ClassElement && parent.name != 'Object') {
      return _documentToJson(parent);
    }
    return null;
  }

  void _checkVirtual(
    ClassElement element,
    List<_Field> columns,
    String? module,
    String? tokenizer,
  ) {
    final vectors = columns.where((field) => field.kind == 'vector').toList();
    if (module == null) {
      for (final field in columns.where((field) => field.document)) {
        if (field.keyOrder != null) {
          invalid(
            'G013',
            '@DbDocument cannot be a primary key.',
            field.element,
          );
        }
        if (field.version) {
          invalid(
            'G013',
            '@DbDocument cannot be the version column.',
            field.element,
          );
        }
      }
      if (tokenizer != null || vectors.isNotEmpty) {
        invalid(
          'G013',
          'A tokenizer or @DbVector needs module fts5 or vec0.',
          element,
        );
      }
      final json = columns.where((field) => field.json).toList();
      if (json.any((field) => field.kind != 'text')) {
        invalid('G013', '@DbJson needs a String column.', element);
      }
      if (json.length == 1 &&
          (json.single.name == 'path' ||
              columns.any((field) => field.name == 'path'))) {
        invalid(
          'G011',
          'The property path conflicts with the JSON helper. '
              'Use manual metadata for this property.',
          element,
        );
      }
      if (json.length > 1 &&
          json.any(
            (field) =>
                columns.any((other) => other.name == '${field.name}Path'),
          )) {
        invalid(
          'G011',
          'A JSON helper name conflicts with a mapped property.',
          element,
        );
      }
      return;
    }
    if (module != 'fts5' && module != 'rtree' && module != 'vec0') {
      invalid('G013', 'DbEntity.module must be fts5, rtree, or vec0.', element);
    }
    if (tokenizer != null && (module != 'fts5' || !_identifier(tokenizer))) {
      invalid(
        'G013',
        'DbEntity.tokenizer is an identifier on an fts5 table.',
        element,
      );
    }
    if (module != 'vec0' && vectors.isNotEmpty) {
      invalid('G013', '@DbVector belongs on a vec0 table.', element);
    }
    if (columns.any(
      (field) =>
          field.json ||
          field.document ||
          field.version ||
          field.unique ||
          field.defaultSql != null ||
          field.reference != null,
    )) {
      invalid(
        'G013',
        'A virtual table cannot map JSON, a document, version, unique, '
            'default, or reference columns.',
        element,
      );
    }
    if (module == 'fts5') {
      final content = columns.where((field) => field.keyOrder == null);
      if (columns.where((field) => field.keyOrder != null).length != 1 ||
          _lower(
                columns.firstWhere((field) => field.keyOrder != null).sqlName,
              ) !=
              'rowid' ||
          content.isEmpty ||
          content.any((field) => field.kind != 'text')) {
        invalid(
          'G013',
          'fts5 needs one rowid key and one or more String columns.',
          element,
        );
      }
      return;
    }
    if (module == 'vec0') {
      final content = columns.where((field) => field.keyOrder == null);
      final key = columns.where((field) => field.keyOrder != null).toList();
      if (key.length != 1 ||
          _lower(key.single.sqlName) != 'rowid' ||
          !const {'integer', 'bigInt'}.contains(key.single.kind) ||
          content.length != 1 ||
          vectors.length != 1 ||
          columns.any(
            (field) =>
                _lower(field.name) == 'distance' ||
                _lower(field.name) == 'k' ||
                _lower(field.sqlName) == 'distance' ||
                _lower(field.sqlName) == 'k',
          )) {
        invalid(
          'G013',
          'vec0 needs one rowid key and one List<double> @DbVector column. '
              'distance and k are reserved.',
          element,
        );
      }
      return;
    }
    const bounds = ['minX', 'maxX', 'minY', 'maxY'];
    final coordinates = columns.where((field) => field.keyOrder == null);
    final key = columns.where((field) => field.keyOrder != null).toList();
    if (columns.first.keyOrder == null ||
        key.length != 1 ||
        key.single.generated ||
        !const {'integer', 'bigInt'}.contains(key.single.kind) ||
        coordinates.length != bounds.length ||
        !bounds.every(
          (name) => coordinates.any(
            (field) => field.name == name && field.kind == 'real',
          ),
        ) ||
        columns.any((field) => field.name == 'bounds')) {
      invalid(
        'G013',
        'rtree needs an integer key first, then double minX, maxX, minY, and maxY.',
        element,
      );
    }
  }

  bool directlyInitializes(ConstructorElement constructor, FieldElement field) {
    final parameter = constructor.formalParameters
        .where((parameter) => parameter.name == field.name)
        .firstOrNull;
    if (parameter is FieldFormalParameterElement && parameter.field == field) {
      return true;
    }
    final unit =
        units[p.normalize(
          constructor.firstFragment.libraryFragment.source.fullName,
        )]!;
    for (final declaration
        in unit.unit.declarations.whereType<ClassDeclaration>()) {
      for (final member
          in declaration.body.members.whereType<ConstructorDeclaration>()) {
        if (member.declaredFragment?.element != constructor) continue;
        return member.initializers.whereType<ConstructorFieldInitializer>().any(
          (initializer) {
            final expression = initializer.expression;
            return initializer.fieldName.name == field.name &&
                expression is SimpleIdentifier &&
                expression.element == parameter;
          },
        );
      }
    }
    return false;
  }

  String sourceType(
    FieldElement field, {
    bool canonical = false,
    bool nonNullable = false,
  }) {
    final unit =
        units[p.normalize(field.firstFragment.libraryFragment.source.fullName)];
    for (final declaration
        in unit!.unit.declarations.whereType<ClassDeclaration>()) {
      for (final member
          in declaration.body.members.whereType<FieldDeclaration>()) {
        if (member.fields.variables.any(
          (variable) => variable.declaredFragment?.element == field,
        )) {
          final annotation = member.fields.type;
          if (annotation != null && !canonical) return annotation.toSource();
        }
      }
    }
    final type = field.type as InterfaceType;
    final name = type.element.name!;
    for (final import in _imports(library)) {
      if (_importDeferred(import)) continue;
      if (_importLookup(import, name) == type.element &&
          (import.prefix != null ||
              _visibleUnprefixed(library, name, type.element))) {
        final prefix = _importPrefix(import);
        return '${prefix == null ? '' : '$prefix.'}'
            '$name${!nonNullable && type.nullabilitySuffix == NullabilitySuffix.question ? '?' : ''}';
      }
    }
    if (_libraryUri(type.element.library) == _libraryUri(library)) {
      return '$name'
          '${!nonNullable && type.nullabilitySuffix == NullabilitySuffix.question ? '?' : ''}';
    }
    invalid(
      'G006',
      'The inferred type $name is hidden in this library. '
          'Write an explicit supported type annotation.',
      field,
    );
  }

  void checkModelNames(List<_Model> models, LibraryElement library) {
    final tables = <String>{};
    final generated = <String>{'generatedModel'};
    for (final model in models) {
      if (!tables.add(_lower(model.table))) {
        error(
          'G007',
          'Duplicate SQL table name ${model.table}.',
          model.element,
        );
      }
      generated.addAll([
        '${model.name}Columns',
        '${model.name}Mapping',
        '${model.name}Relationships',
      ]);
    }
    for (final element in _topLevel(library)) {
      if (_elementPath(element) != output && generated.contains(element.name)) {
        error(
          'G011',
          'Generated identifier ${element.name} already exists.',
          element,
        );
      }
    }
    for (final import in _imports(library)) {
      final prefix = import.prefix?.element;
      if (prefix != null && generated.contains(prefix.name)) {
        error(
          'G011',
          'Generated identifier ${prefix.name} conflicts with an '
              'import prefix.',
          prefix,
        );
      }
    }
  }

  List<_Relationship> relationships(List<_Model> models) {
    final result = <_Relationship>[];
    for (final child in models) {
      final helperNames = <String>{};
      for (final field in child.fields) {
        final annotation = field.reference;
        _Model? parent;
        _Field? target;
        var action = 'noAction';
        if (annotation != null) {
          final type = annotation.getField('target')?.toTypeValue();
          if (type is InterfaceType) {
            parent = models
                .where((model) => model.element == type.element)
                .firstOrNull;
          }
          if (parent == null) {
            error(
              'G012',
              'DbReference target must be a selected model.',
              field.element,
            );
            continue;
          }
          final property = annotation.getField('column')?.toStringValue();
          target = property == null
              ? parent.keys.length == 1
                    ? parent.keys.single
                    : null
              : parent.fields
                    .where((candidate) => candidate.name == property)
                    .firstOrNull;
          final index =
              annotation
                  .getField('onDelete')
                  ?.getField('index')
                  ?.toIntValue() ??
              0;
          const actions = [
            'noAction',
            'restrict',
            'cascade',
            'setNull',
            'setDefault',
          ];
          if (index >= 0 && index < actions.length) action = actions[index];
        } else {
          final candidates = models
              .where(
                (model) =>
                    model != child &&
                    model.keys.length == 1 &&
                    model.keys.single.kind == field.kind &&
                    _lower(field.name) == '${_lower(model.name)}id',
              )
              .toList();
          if (candidates.length == 1) {
            parent = candidates.single;
            target = parent.keys.single;
          }
        }
        if (parent == null) continue;
        if (child.module != null || parent.module != null) {
          error(
            'G013',
            'Virtual tables cannot own or target a foreign key.',
            field.element,
          );
          continue;
        }
        if (target == null ||
            !(parent.keys.length == 1 && target == parent.keys.single ||
                target.unique) ||
            field.kind != target.kind ||
            action == 'setNull' && !field.nullable ||
            action == 'setDefault' &&
                !field.nullable &&
                field.defaultSql == null) {
          error(
            'G012',
            'Foreign keys need a compatible unique target and '
                'valid null/default actions.',
            field.element,
          );
          continue;
        }
        var helper = field.name.endsWith('Id') && field.name.length > 2
            ? field.name.substring(0, field.name.length - 2)
            : field.name;
        if (const {
              'hashCode',
              'runtimeType',
              'toString',
              'noSuchMethod',
            }.contains(helper) ||
            !helperNames.add(helper)) {
          helper = field.name;
          if (!helperNames.add(helper)) {
            error(
              'G012',
              'Relationship helper name is ambiguous.',
              field.element,
            );
            continue;
          }
        }
        result.add(_Relationship(child, parent, field, target, helper, action));
      }
    }
    return result;
  }
}

bool _validSqlName(String value) =>
    value.isNotEmpty && !value.contains('\u0000');

String? _jsonMapKind(DartType type) {
  if (type is! InterfaceType ||
      type.element.name != 'Map' ||
      _libraryUri(type.element.library) != 'dart:core' ||
      type.typeArguments.length != 2) {
    return null;
  }
  final key = type.typeArguments[0];
  if (key is! InterfaceType ||
      key.element.name != 'String' ||
      _libraryUri(key.element.library) != 'dart:core' ||
      key.nullabilitySuffix == NullabilitySuffix.question) {
    return null;
  }
  final value = type.typeArguments[1];
  if (value is DynamicType) return 'dynamic';
  if (value is InterfaceType &&
      value.element.name == 'Object' &&
      _libraryUri(value.element.library) == 'dart:core' &&
      value.nullabilitySuffix == NullabilitySuffix.question) {
    return 'object';
  }
  return null;
}

bool _returnsJsonMap(DartType type) {
  if (type is DynamicType) return true;
  return type is InterfaceType &&
      type.element.name == 'Map' &&
      _libraryUri(type.element.library) == 'dart:core';
}

bool _identifier(String value) =>
    RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(value);

bool _isDoubleList(DartType type) {
  if (type is! InterfaceType || type.element.name != 'List') return false;
  if (type.typeArguments.length != 1) return false;
  final argument = type.typeArguments.single;
  return argument is InterfaceType &&
      argument.element.name == 'double' &&
      argument.nullabilitySuffix != NullabilitySuffix.question &&
      _libraryUri(argument.element.library) == 'dart:core';
}

String? _kind(DartType type) {
  if (type is! InterfaceType) return null;
  final uri = _libraryUri(type.element.library);
  if (uri == 'dart:typed_data' && type.element.name == 'Uint8List') {
    return 'blob';
  }
  if (uri != 'dart:core') return null;
  return switch (type.element.name) {
    'BigInt' => 'bigInt',
    'int' => 'integer',
    'double' => 'real',
    'bool' => 'boolean',
    'String' => 'text',
    'DateTime' => 'dateTime',
    _ => null,
  };
}

final class _Field {
  _Field(
    this.element,
    this.kind,
    this.dartType,
    this.keyType, {
    required this.nullable,
    required this.sqlName,
    required this.unique,
    required this.explicitKey,
    required this.generated,
    required this.version,
    required this.json,
    this.documentFromJson,
    this.keyOrder,
    this.defaultSql,
    this.reference,
    this.vectorDimensions,
    this.vectorMetric,
  });
  final FieldElement element;
  final String kind, sqlName, dartType, keyType;
  final bool nullable, unique, explicitKey, version, json;
  final String? documentFromJson;
  final int? vectorDimensions;
  final String? vectorMetric;
  bool generated;
  int? keyOrder;
  final String? defaultSql;
  final DartObject? reference;
  String get name => element.name!;
  bool get document => kind == 'document';
  bool get writable => !element.isFinal && element.setter != null;
  String codec(String prefix) {
    if (document) {
      final body =
          '${prefix}Codecs.document($documentFromJson, (value) => value.toJson())';
      return nullable ? '${prefix}Codecs.nullable($body)' : body;
    }
    if (kind == 'vector') return '${prefix}Codecs.vector($vectorDimensions)';
    return nullable
        ? '${prefix}Codecs.nullable(${prefix}Codecs.$kind)'
        : '${prefix}Codecs.$kind';
  }
}

final class _Scalar {
  _Scalar(
    this.element,
    this.name,
    this.sqlName,
    this.fields,
    this.returnType,
    this.getter,
  );
  final ExecutableElement element;
  final String name, sqlName, returnType;
  final List<_Field> fields;
  final bool getter;
}

final class _ScalarReads extends RecursiveAstVisitor<void> {
  _ScalarReads(this.owner, this.fields);
  final ClassElement owner;
  final List<_Field> fields;
  final Set<FieldElement> reads = {};
  String? failure;

  @override
  void visitAssignmentExpression(AssignmentExpression node) {
    final left = node.leftHandSide;
    final field = left is SimpleIdentifier ? _scalarField(left.element) : null;
    if (field != null && field.enclosingElement == owner) {
      failure ??= '@DbScalar does not assign ${field.name}.';
    }
    super.visitAssignmentExpression(node);
  }

  @override
  void visitMethodInvocation(MethodInvocation node) {
    final target = node.realTarget;
    final invoked = node.methodName.element;
    if ((target == null || target is ThisExpression) &&
        invoked is ExecutableElement &&
        invoked.enclosingElement == owner) {
      failure ??=
          '@DbScalar reads mapped fields directly. ${node.methodName.name}() stays outside the body.';
    }
    super.visitMethodInvocation(node);
  }

  @override
  void visitSimpleIdentifier(SimpleIdentifier node) {
    final field = _scalarField(node.element);
    if (field != null && !field.isStatic && field.enclosingElement == owner) {
      if (fields.any((candidate) => candidate.element == field)) {
        reads.add(field);
      } else {
        failure ??=
            '@DbScalar can read mapped fields. ${field.name} is not mapped.';
      }
    }
    super.visitSimpleIdentifier(node);
  }
}

FieldElement? _scalarField(Element? element) {
  if (element is FieldElement) return element;
  if (element is PropertyAccessorElement) {
    final variable = element.variable;
    if (variable is FieldElement) return variable;
  }
  return null;
}

String _scalarSqlName(String table, String method) {
  final raw = '${_lower(table)}_${_lower(method)}';
  final units = raw.codeUnits.map((unit) {
    final digit = unit >= 48 && unit <= 57;
    final letter = (unit >= 65 && unit <= 90) || (unit >= 97 && unit <= 122);
    return digit || letter || unit == 95 ? unit : 95;
  });
  var name = String.fromCharCodes(units).replaceAll(RegExp(r'_+'), '_');
  if (name.startsWith(RegExp(r'[0-9]'))) name = 's_$name';
  if (name.isEmpty || name == '_') name = 'scalar';
  return name;
}

String _scalarRegistration(_Model model, _Scalar scalar, String prefix) {
  final body = StringBuffer();
  for (var index = 0; index < scalar.fields.length; index++) {
    final field = scalar.fields[index];
    body.writeln(
      'final ${field.name} = scalarArguments[$index] == null ? null : '
      '${model.name}Columns.${field.name}.decodeValue(scalarArguments[$index]);',
    );
    if (!field.nullable) {
      body.writeln('if (${field.name} == null) return null;');
    }
  }
  final arguments = <String>[];
  for (final parameter in model.constructor.formalParameters) {
    final field = model.fields
        .where((field) => field.name == parameter.name)
        .firstOrNull;
    if (field == null) continue;
    final read = scalar.fields.any((item) => item.name == field.name);
    final value = read ? field.name : _scalarPlaceholder(field);
    arguments.add(parameter.isNamed ? '${parameter.name}: $value' : value);
  }
  final call = scalar.getter ? scalar.name : '${scalar.name}()';
  body.write(
    'return ${model.name}'
    '${_unnamedConstructor(model.constructor) ? '' : '.${model.constructor.name}'}'
    '(${arguments.join(',')}).$call;',
  );
  return '${prefix}EntityScalar<${model.name}>('
      'name: ${_string(scalar.sqlName)}, '
      'columns: [${scalar.fields.map((field) => '${model.name}Columns.${field.name}').join(', ')}], '
      'apply: (scalarArguments) { $body },),';
}

String _scalarPlaceholder(_Field field) {
  if (field.nullable) return 'null';
  return switch (field.kind) {
    'bigInt' => 'BigInt.zero',
    'integer' => '0',
    'real' => '0.0',
    'boolean' => 'false',
    'text' => "''",
    'dateTime' => 'DateTime.utc(1970)',
    'blob' => 'Uint8List(0)',
    'vector' => 'const <double>[]',
    _ => 'null',
  };
}

