/// Explicit relationship access. Loading performs I/O; obtaining a handle or
/// linking tracked entries does not.
extension EntityRelationships<T> on EntityEntry<T> {
  EntityReference<T, P> reference<P>(ForeignKey<T, P> relation) {
    _checkRelationshipEntry(this, relation.child);
    _checkRegisteredRelationship(context, relation);
    return EntityReference<T, P>._(this, relation);
  }

  EntityCollection<C, T> collection<C>(ForeignKey<C, T> relation) {
    _checkRelationshipEntry(this, relation.parent);
    _checkRegisteredRelationship(context, relation);
    return EntityCollection<C, T>._(this, relation);
  }
}

final class EntityReference<C, P> {
  EntityReference._(this.entry, this.relation);
  final EntityEntry<C> entry;
  final ForeignKey<C, P> relation;

  /// Returns the tracked parent, or null for an optional missing reference.
  /// An explicit pending link is resolved without querying the store.
  Future<P?> load() async =>
      (await entry.context.loadReferences(relation, [entry]))[entry];

  /// Records an explicit unit-of-work link. Store-generated keys and dependent
  /// foreign-key fields are published only after the entire save commits.
  void set(EntityEntry<P>? parent) =>
      entry.context._setRelationshipLink(entry, relation, parent);
}

final class EntityCollection<C, P> {
  EntityCollection._(this.entry, this.relation);
  final EntityEntry<P> entry;
  final ForeignKey<C, P> relation;

  Future<List<C>> load() async =>
      (await entry.context.loadCollections(relation, [entry]))[entry]!;

  /// Links a tracked child, including when this parent's key is generated by
  /// the next save. No entity graph is attached implicitly.
  void add(EntityEntry<C> child) => child.reference(relation).set(entry);

  /// Clears an optional relationship. Required relationships must instead be
  /// reassigned or the child explicitly removed from its set.
  void remove(EntityEntry<C> child) {
    _checkRelationshipEntry(entry, relation.parent);
    _checkRelationshipEntry(child, relation.child);
    if (!identical(child.context, entry.context)) {
      throw const OrmStateException(
          'Relationship entries belong to different contexts');
    }
    final links = entry.context._relationshipLinks[child];
    if (links != null && links.containsKey(relation)) {
      entry.context._validateRelationshipLinks(child);
      if (!identical(links[relation], entry)) {
        throw const OrmStateException('Child is linked to a different parent');
      }
    } else {
      final parentKey =
          _relationshipEntityKey(relation.targetColumns, entry.entity);
      final childKey = _relationshipEntityKey(relation.columns, child.entity);
      if (parentKey == null || childKey != parentKey) {
        throw const OrmStateException('Child does not belong to this parent');
      }
    }
    child.reference(relation).set(null);
  }
}

/// Batch eager loading with bounded parameter lists. Results use the context's
/// identity map and preserve local changes on already tracked entities.
extension RelationshipLoading on DbContext {
  Future<Map<EntityEntry<C>, P?>> loadReferences<C, P>(
      ForeignKey<C, P> relation, Iterable<EntityEntry<C>> children) {
    final entries = List<EntityEntry<C>>.of(children);
    _checkRegisteredRelationship(this, relation);
    for (final entry in entries) {
      _checkRelationshipEntry(entry, relation.child);
      if (!identical(entry.context, this)) {
        throw const OrmStateException(
            'Relationship entries belong to different contexts');
      }
    }
    return _serialize(() async {
      final result = Map<EntityEntry<C>, P?>.identity();
      final wanted = <EntityKey, List<EntityEntry<C>>>{};
      for (final entry in entries) {
        _checkRelationshipEntry(entry, relation.child);
        final links = _relationshipLinks[entry];
        if (links != null && links.containsKey(relation)) {
          _validateRelationshipLinks(entry);
          final parent = links[relation];
          if (parent != null) {
            _checkRelationshipEntry(parent, relation.parent);
          }
          result[entry] = parent?.entity as P?;
          continue;
        }
        final key = _relationshipEntityKey(relation.columns, entry.entity);
        if (key == null) {
          result[entry] = null;
        } else {
          (wanted[key] ??= []).add(entry);
        }
      }
      final parents = <EntityKey, P>{};
      for (final chunk
          in _relationshipChunks(wanted.keys, relation.targetColumns.length)) {
        final predicate = _relationshipPredicate(relation.targetColumns, chunk);
        final rows = await connection.query(
            'SELECT ${_relationshipProjection(relation.parent)} '
            'FROM ${quoteIdentifier(relation.parent.tableName)} '
            'WHERE ${predicate.$1}',
            predicate.$2);
        for (final values in rows.rows) {
          final reader = _relationshipReader(rows.columns, values);
          final key = _relationshipReaderKey(relation.targetColumns, reader);
          if (key == null || parents.containsKey(key)) {
            throw const OrmStateException(
                'Relationship target is not unique in the store');
          }
          parents[key] = _materialize(relation.parent, reader);
        }
      }
      final required = relation.columns.every((column) => !column.nullable);
      for (final request in wanted.entries) {
        final parent = parents[request.key];
        if (parent == null && required) {
          throw OrmStateException(
              'Required parent for ${relation.name} is missing');
        }
        for (final entry in request.value) {
          result[entry] = parent;
        }
      }
      return Map<EntityEntry<C>, P?>.unmodifiable(result);
    });
  }

  Future<Map<EntityEntry<P>, List<C>>> loadCollections<C, P>(
      ForeignKey<C, P> relation, Iterable<EntityEntry<P>> parents) {
    final entries = List<EntityEntry<P>>.of(parents);
    _checkRegisteredRelationship(this, relation);
    for (final entry in entries) {
      _checkRelationshipEntry(entry, relation.parent);
      if (!identical(entry.context, this)) {
        throw const OrmStateException(
            'Relationship entries belong to different contexts');
      }
    }
    return _serialize(() async {
      final result = Map<EntityEntry<P>, List<C>>.identity();
      final wanted = <EntityKey, EntityEntry<P>>{};
      for (final entry in entries) {
        _checkRelationshipEntry(entry, relation.parent);
        result[entry] = [];
        final key =
            _relationshipEntityKey(relation.targetColumns, entry.entity);
        if (key == null) continue;
        final previous = wanted[key];
        if (previous != null && !identical(previous, entry)) {
          throw const OrmStateException(
              'Tracked parents have ambiguous relationship target values');
        }
        wanted[key] = entry;
      }
      for (final chunk
          in _relationshipChunks(wanted.keys, relation.columns.length)) {
        final predicate = _relationshipPredicate(relation.columns, chunk);
        final rows = await connection.query(
            'SELECT ${_relationshipProjection(relation.child)} '
            'FROM ${quoteIdentifier(relation.child.tableName)} '
            'WHERE ${predicate.$1}',
            predicate.$2);
        for (final values in rows.rows) {
          _materialize(
              relation.child, _relationshipReader(rows.columns, values));
        }
      }
      // Current tracked FK values and explicit links take precedence over old
      // store values. This also includes newly linked, unsaved children.
      for (final candidate in _entries.values.toList(growable: false)) {
        if (!identical(candidate.type, relation.child) ||
            candidate.state == EntityState.deleted ||
            candidate.state == EntityState.detached) {
          continue;
        }
        final child = candidate as EntityEntry<C>;
        EntityEntry<P>? parent;
        final links = _relationshipLinks[child];
        if (links != null && links.containsKey(relation)) {
          _validateRelationshipLinks(child);
          parent = links[relation] as EntityEntry<P>?;
        } else {
          final key = _relationshipEntityKey(relation.columns, child.entity);
          if (key != null) parent = wanted[key];
        }
        if (parent != null && result.containsKey(parent)) {
          result[parent]!.add(child.entity);
        }
      }
      return Map<EntityEntry<P>, List<C>>.unmodifiable({
        for (final entry in result.entries)
          entry.key: List<C>.unmodifiable(entry.value)
      });
    });
  }
}

void _checkRegisteredRelationship(
    DbContext context, ForeignKey<dynamic, dynamic> relation) {
  if (!context.model.foreignKeys.contains(relation)) {
    throw const OrmMappingException(
        'Relationship is not registered in this context model');
  }
}

void _checkRelationshipEntry<T>(
    EntityEntry<dynamic> entry, EntityType<T> expected) {
  if (!identical(entry.type, expected)) {
    throw const OrmMappingException('Relationship has the wrong entity type');
  }
  if (entry.state == EntityState.detached ||
      entry.state == EntityState.deleted) {
    throw const OrmStateException(
        'Relationship entry must be active and tracked');
  }
}

EntityKey? _relationshipEntityKey<T>(
    List<Column<T, dynamic>> columns, T entity) {
  final values = [for (final column in columns) column.readEncoded(entity)];
  return values.any((value) => value == null) ? null : EntityKey(values);
}

EntityKey? _relationshipReaderKey<T>(
    List<Column<T, dynamic>> columns, RowReader reader) {
  final values = [
    for (final column in columns)
      column.encodeValue(column.decodeValue(reader.raw(column.sqlName)))
  ];
  return values.any((value) => value == null) ? null : EntityKey(values);
}

String _relationshipProjection<T>(EntityType<T> type) =>
    type.columns.map((column) => quoteIdentifier(column.sqlName)).join(',');

RowReader _relationshipReader(List<String> columns, List<Object?> values) =>
    RowReader({for (var i = 0; i < columns.length; i++) columns[i]: values[i]});

Iterable<List<EntityKey>> _relationshipChunks(
    Iterable<EntityKey> keys, int width) sync* {
  if (width < 1 || width > 900) {
    throw const OrmMappingException(
        'Relationship keys must have 1 to 900 columns');
  }
  final maximum = 900 ~/ width;
  var chunk = <EntityKey>[];
  for (final key in keys) {
    chunk.add(key);
    if (chunk.length == maximum) {
      yield chunk;
      chunk = [];
    }
  }
  if (chunk.isNotEmpty) yield chunk;
}

(String, List<Object?>) _relationshipPredicate<T>(
    List<Column<T, dynamic>> columns, List<EntityKey> keys) {
  final names =
      columns.map((column) => quoteIdentifier(column.sqlName)).toList();
  final placeholders = columns.length == 1
      ? '?'
      : '(${List.filled(columns.length, '?').join(',')})';
  final operand = columns.length == 1 ? names.single : '(${names.join(',')})';
  return (
    '$operand IN (${List.filled(keys.length, placeholders).join(',')})',
    [for (final key in keys) ...key.values]
  );
}
